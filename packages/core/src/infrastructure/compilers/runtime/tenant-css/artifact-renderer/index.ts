/**
 * @fileoverview Deterministic renderer for first-party tenant CSS artifacts.
 *
 * Dynamic, DB-driven tenant visual composition belongs to the composition
 * tier. This compiler owns only the static artifact format and selector-scope
 * projection, so it remains independent of runtime registries and peer
 * compilers.
 */

import type { BrandExpressiveSelection } from '@/foundation/contracts/composition/tenants/themes';
import type {
  ThemeCompilation,
  ThemeCompilationModeBlock,
} from '@/foundation/contracts/composition/tenants/themes/compiled';
import type { ThemeResolution } from '@/foundation/contracts/composition/tenants/themes/resolved';
import type { FirstPartyVerticalId } from '@/foundation/contracts/kernel/verticals';
import { FIRST_PARTY_VERTICAL_ROSTER } from '@/foundation/presets/verticals/roster';
import {
  compileThemeIntent,
  containerScope,
  emitBaseRule,
  emitModeRule,
  firstPartyScope,
  staticThemeIntent,
} from '../../theme';
import { readGovernedTheme } from '../../theme/runtime/lowering/foundation/intake';
import { brandThemeToPersonality } from '../../theme/runtime/lowering/foundation/personality';
import { projectFirstPartyArtifactScopes } from '../../../kernel/foundation/css/scope-projection';

/** Marker written at the top of every generated vertical artifact. */
export const GENERATED_ARTIFACT_BANNER = 'GENERATED — do not edit';

/** Command shown in generated headers and used by the artifact guard. */
export const FIRST_PARTY_ARTIFACT_REGENERATE_COMMAND =
  'pnpm -C ui-design-system/packages/core build:vertical-css';

/** Static description of a first-party vertical artifact this generator owns. */
export interface FirstPartyArtifactSpec {
  /** Tenant slug, e.g. `'bithire'`. */
  slug: FirstPartyVerticalId;
  /**
   * Vertical baseline projected onto provider roots.
   *
   * Equal to `slug`, always. It is kept as its own field because the renderer
   * and the scope projection both read it by name, but it is DERIVED, never
   * authored: this field is where the roster inversion lived, spelling
   * a mismatched vertical key under the Rottay slug and forcing every
   * downstream consumer to carry both keys to survive.
   */
  verticalKey: FirstPartyVerticalId;
  /** Human-facing product name for the header banner. */
  displayName: string;
  /** Selector the compiled variable block is scoped to. */
  selector: string;
  /** Path to the authored theme, relative to `packages/core/src`. */
  authoredThemePath: string;
  /**
   * Path to the vertical's preset document, relative to `packages/core/src`.
   *
   * The artifact compiles from this document admitted over the neutral
   * foundation, so it is the source the generated header names.
   */
  presetDocumentPath: string;
}

/**
 * The document-root arm of a vertical's scope.
 *
 * The roster's `selector` is the full two-arm form — a legacy
 * `html[data-tenant]` arm plus a nested `[data-ds-root][data-vertical]` arm.
 * A generated artifact is scoped to the DOCUMENT-ROOT arm only, because the
 * artifact is the top-level stylesheet a host page loads. Deriving it here
 * rather than restating a literal keeps the two spellings one fact;
 * `tests/roster-projection.test.ts` asserts this string is literally a
 * substring of the roster's own selector for the same slug, so the two cannot
 * drift into disagreement.
 */
function artifactRootSelector(slug: FirstPartyVerticalId): string {
  return `html[data-tenant='${slug}']`;
}

function presetDocumentPath(slug: FirstPartyVerticalId): string {
  return `foundation/presets/verticals/${slug}/document/index.json`;
}

/**
 * First-party vertical artifacts regenerated by `build:vertical-artifacts`.
 *
 * PROJECTED FROM THE ROSTER, not restated. Every field below is a function of
 * one roster row. This array used to be a hand-maintained table, which is how
 * it came to claim a Rottay slug with a mismatched vertical key — a mapping no
 * other authority agreed with, pinned in place by a scope-projection test that
 * asserted the inversion was correct.
 *
 * Customer tenants are deliberately excluded: their DB-owned documents are
 * compiled dynamically and must never receive a precompiled artifact.
 */
export const FIRST_PARTY_ARTIFACT_SPECS: readonly FirstPartyArtifactSpec[] =
  Object.freeze(
    FIRST_PARTY_VERTICAL_ROSTER.map((row) =>
      Object.freeze({
        slug: row.slug,
        verticalKey: row.verticalKey,
        displayName: row.name,
        authoredThemePath: row.themeSourcePath,
        presetDocumentPath: presetDocumentPath(row.slug),
        selector: artifactRootSelector(row.slug),
      }),
    ),
  );

/** Inputs for {@link renderVerticalArtifact}. */
export interface RenderVerticalArtifactInput {
  tenantSlug: string;
  verticalKey: string;
  authoredThemePath: string;
  displayName: string;
  selector: string;
  compiledCssVariables: Record<string, string>;
  /** Declared default mode of the compiled values; emitted as `color-scheme`. */
  colorScheme?: 'light' | 'dark';
  /** Compiled deltas for every mode the theme authors beyond its default. */
  modeBlocks?: readonly ThemeCompilationModeBlock[];
  regenerateCommand: string;
}

/** Render a first-party vertical CSS artifact as a deterministic build output. */
export function renderVerticalArtifact(input: RenderVerticalArtifactInput): string {
  const {
    tenantSlug,
    verticalKey,
    authoredThemePath,
    displayName,
    selector,
    compiledCssVariables,
    colorScheme,
    modeBlocks,
    regenerateCommand,
  } = input;

  const header = [
    `/* ${GENERATED_ARTIFACT_BANNER} */`,
    '/*',
    ` * ${displayName} tenant theme.`,
    ' *',
    ' * This file is a BUILD OUTPUT compiled from ONE authored source; any manual',
    ' * edit is reverted by the DS artifact parity/guard gates:',
    ` *   ${authoredThemePath} (compiled via compileTheme)`,
    ' *',
    ` * Regenerate: ${regenerateCommand}`,
    ' */',
  ].join('\n');

  // The document-root ink is artifact-format semantics, not theme content: this
  // file is the top-level stylesheet a host page loads, so it owns the root
  // chrome declaration. It is welded to the channel NAME and never to a value:
  // a DB tenant moves the same ink by moving --ds-color-text-primary through the
  // shared compileTheme lowering, and a compile that leaves the channel to the
  // DS foundation paints the foundation's own default through the same var().
  // The artifact never authors the value itself: a blank channel is refused
  // rather than declared, because it would be an ink nobody authored.
  const rootInk = compiledCssVariables['--ds-color-text-primary'];
  if (rootInk !== undefined && rootInk.trim() === '') {
    throw new Error(
      `renderVerticalArtifact: ${tenantSlug} compiled a blank --ds-color-text-primary; ` +
        'the artifact cannot author the document root ink in its place.',
    );
  }

  // The RULE is the emission owner's grammar; the artifact owns its ORDER (sorted,
  // so a diff of two builds is readable) and the root ink, which is
  // artifact-format semantics rather than theme content.
  const sortedVariables = Object.fromEntries(
    Object.keys(compiledCssVariables)
      .sort()
      .map((key) => [key, compiledCssVariables[key] as string]),
  );
  // Two scopes, because the artifact has two: the BASE rule is scoped to the
  // spec's own selector (a caller may re-gate it, and a test does), while the
  // MODE rules are scoped to the slug's own mode grammar exactly as before.
  const baseScope = containerScope(selector);
  const modeScope = firstPartyScope(tenantSlug as FirstPartyVerticalId);
  const compiledBlock = [
    '/* === Compiled from the authored Theme via compileTheme — do not edit === */',
    emitBaseRule(
      { cssVariables: sortedVariables, modeBlocks: [], ...(colorScheme ? { colorScheme } : {}),
        runtime: { personality: {}, tokenOverrides: {} } },
      baseScope,
      { leadingDeclarations: ['  color: var(--ds-color-text-primary);'] },
    ),
  ].join('\n');

  // One block per authored non-default mode, from Theme.modes. Each holds
  // only the channels that mode moves; the base block above still supplies the
  // rest. These used to be hand-written blocks in the declared extension source,
  // which made that source a second theme author for every state but the default
  // one. That authority no longer exists: this renderer has one authored input.
  const modeBlockSections = (modeBlocks ?? []).map((block) =>
    [
      `/* === Compiled from Theme.modes.${block.mode} — do not edit === */`,
      emitModeRule(
        {
          mode: block.mode,
          colorScheme: block.colorScheme,
          cssVariables: Object.fromEntries(
            Object.keys(block.cssVariables)
              .sort()
              .map((key) => [key, block.cssVariables[key] as string]),
          ),
        },
        modeScope,
      ),
    ].join('\n'),
  );

  return projectFirstPartyArtifactScopes(
    [header, compiledBlock, ...modeBlockSections].join('\n\n') + '\n',
    tenantSlug,
    verticalKey,
  );
}

/** Inputs for {@link renderFirstPartyArtifact}. */
export interface RenderFirstPartyArtifactInput {
  spec: FirstPartyArtifactSpec;
  regenerateCommand?: string;
}

/**
 * The governed, non-CSS half of a first-party compile beside its recipe
 * selection: what the vertical DECIDED, as names and dials, never as paint.
 */
export interface FirstPartyGovernedBehavior {
  readonly motion?: {
    readonly intensity?: number;
    readonly entranceDuration?: number;
  };
  readonly expressive?: BrandExpressiveSelection;
  readonly decidedChannels?: readonly string[];
}

const PERSONALITY_DIMENSIONS = ['animation', 'typography', 'accent', 'card'] as const;

/**
 * Read the vertical's decisions off its resolved baseline. The neutral
 * foundation states no personality leaf and no motion dial, so every defined
 * leaf here is the preset's own decision; a channel is listed by name only.
 */
export function firstPartyGovernedBehavior(resolution: ThemeResolution): FirstPartyGovernedBehavior {
  const view = readGovernedTheme(resolution.theme);
  const personality = brandThemeToPersonality(view);
  const decidedChannels: string[] = [];
  for (const dimension of PERSONALITY_DIMENSIONS) {
    const values = personality[dimension];
    if (!values) continue;
    for (const [field, value] of Object.entries(values)) {
      if (value !== undefined) decidedChannels.push(`${dimension}.${field}`);
    }
  }
  if (view.surfaces?.density !== undefined) decidedChannels.push('card.paddingDensity');
  const intensity = view.motion?.intensity;
  const entranceDuration = view.motion?.entranceDuration;
  const motion =
    intensity === undefined && entranceDuration === undefined
      ? undefined
      : {
          ...(intensity === undefined ? {} : { intensity }),
          ...(entranceDuration === undefined ? {} : { entranceDuration }),
        };
  // The neutral activates the expressive family with every leaf undecided; a
  // selection the vertical actually made carries its schema version.
  const expressive =
    view.expressive?.schemaVersion === undefined ? undefined : view.expressive;
  return {
    ...(motion === undefined ? {} : { motion }),
    ...(expressive === undefined ? {} : { expressive }),
    ...(decidedChannels.length === 0 ? {} : { decidedChannels }),
  };
}

/**
 * Compile a first-party vertical over the neutral foundation and render its
 * artifact in one call.
 *
 * The build script, the parity tests and the gates each used to assemble
 * {@link RenderVerticalArtifactInput} by hand from the same spec. Three copies
 * of one mapping means a field added to the contract reaches some of them and
 * not others, and the artifact each produces silently disagrees — which is how
 * a caller ends up "regenerating" an artifact into a different file than the
 * build writes. There is one assembly, and it lives here.
 */
export function renderFirstPartyArtifact(input: RenderFirstPartyArtifactInput): {
  css: string;
  compiled: ThemeCompilation;
  governed: FirstPartyGovernedBehavior;
} {
  const { spec, regenerateCommand } = input;
  // The intent NAMES the vertical; the engine is read off that one roster row
  // and the baseline is the neutral foundation with the vertical's preset
  // admitted over it. The theme used to arrive as an input and the engine as
  // `spec.engine`, which let the two disagree -- a caller could render one
  // vertical's theme under another's spec and the artifact header would say
  // the spec's name over the theme's channels.
  const { compiled, resolution } = compileThemeIntent(
    staticThemeIntent(spec.verticalKey, spec.slug),
  );
  return {
    compiled,
    governed: firstPartyGovernedBehavior(resolution),
    css: renderVerticalArtifact({
      tenantSlug: spec.slug,
      verticalKey: spec.verticalKey,
      authoredThemePath: spec.presetDocumentPath,
      displayName: spec.displayName,
      selector: spec.selector,
      compiledCssVariables: compiled.cssVariables,
      colorScheme: compiled.colorScheme,
      modeBlocks: compiled.modeBlocks,
      regenerateCommand: regenerateCommand ?? FIRST_PARTY_ARTIFACT_REGENERATE_COMMAND,
    }),
  };
}
