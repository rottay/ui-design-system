test('repeated-path-word law: the three D2 definitions measure as named, the ruled definition is word-any', () => {
  const files = [
    'packages/core/src/runtime/runtime/index.ts',
    'packages/core/src/runtime/tenant/runtime/index.ts',
    'packages/core/src/data/data-table/index.ts',
  ];
  assert.equal(REPEATED_PATH_WORD_DEFINITION, 'word-any');
  assert.deepEqual(measureRepeatedPathWords(files, 'segment-adjacent'), ['runtime/runtime']);
  assert.deepEqual(measureRepeatedPathWords(files, 'segment-any'), ['runtime/runtime', 'runtime/tenant/runtime']);
  assert.deepEqual(measureRepeatedPathWords(files, 'word-any'), ['data/data-table', 'runtime/runtime', 'runtime/tenant/runtime']);
  assert.throws(() => measureRepeatedPathWords(files, 'nonsense'), /unknown repeated-path-word definition/u);
});

function measured(members) {
  return {
    definitions: lawDefinitions(),
    members: Object.fromEntries(STRUCTURE_LAWS.map((law) => [law, members[law] ?? []])),
  };
}

test('pinning is exact: a new member and a stale pin both fail, the pinned set passes', () => {
  const pinned = measured({ 'single-child-folder': ['a', 'b'] });
  assert.equal(compareStructureLaws(measured({ 'single-child-folder': ['a', 'b'] }), pinned).passed, true);

  const grown = compareStructureLaws(measured({ 'single-child-folder': ['a', 'b', 'c'] }), pinned);
  assert.equal(grown.passed, false);
  assert.deepEqual(grown.added['single-child-folder'], ['c']);

  const shrunk = compareStructureLaws(measured({ 'single-child-folder': ['a'] }), pinned);
  assert.equal(shrunk.passed, false);
  assert.deepEqual(shrunk.stale['single-child-folder'], ['b']);

  const moved = compareStructureLaws(measured({ 'single-child-folder': ['a', 'z'] }), pinned);
  assert.equal(moved.passed, false, 'the same count with a different member is new debt, not a wash');
});

test('a ruled definition change is not absorbed silently: the stored definitions must match', () => {
  const pinned = measured({});
  const reruled = { ...measured({}), definitions: { ...lawDefinitions(), 'repeated-path-word': { ...lawDefinitions()['repeated-path-word'], definition: 'segment-adjacent' } } };
  const comparison = compareStructureLaws(reruled, pinned);
  assert.equal(comparison.passed, false);
  assert.deepEqual(comparison.problems, comparison.problems.filter((problem) => problem.startsWith('repeated-path-word: definition changed')));
  assert.deepEqual(changedLawDefinitions(reruled, pinned), ['repeated-path-word'], 'a D2 flip changes one law, not five');
  assert.equal(compareStructureLaws(measured({}), undefined).passed, false);
});

test('LIVE: the committed baseline pins the measured laws exactly', () => {
  const here = dirname(fileURLToPath(import.meta.url));
  const baseline = JSON.parse(readFileSync(resolve(here, '../baseline/index.json'), 'utf8'));
  const comparison = compareStructureLaws(measureStructureLaws({ repoRoot: resolve(here, '../../../../../../../..') }), baseline.laws);
  assert.deepEqual(comparison.problems, []);
});

