test('the worktree empty-folder registry is an exemption list that may only shrink, and is no definition', () => {
  const original = [
    'entrypoints/icons/legacy',
    'infrastructure/runtime/application/navigation/routing/tests',
    'infrastructure/runtime/application/notifications/tests',
  ];
  assert.ok(REGISTERED_WORKTREE_EMPTY_DIRECTORIES.every((path) => original.includes(path)), 'a new registered folder would launder empty-directory debt');
  assert.equal(JSON.stringify(lawDefinitions()['empty-directory']).includes('legacy'), false);
});

test('the generated-banner exemption is counted, so a self-declared banner is visible every run', () => {
  const texts = {
    'packages/core/src/real/index.ts': lines(LINE_COUNT_LIMIT + 1),
    'packages/core/src/claimed/index.ts': `/* do not edit */\n${lines(5000)}`,
  };
  const exempt = { banner: 0 };
  const authored = authoredFiles(Object.keys(texts), (path) => texts[path], exempt);
  assert.equal(exempt.banner, 1);
  assert.deepEqual(measureLineCount(authored).members, ['packages/core/src/real/index.ts']);
});
