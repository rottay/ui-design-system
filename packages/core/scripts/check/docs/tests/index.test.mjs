test('RED: a generator that cannot run reports UNRUNNABLE under its own finding kind', () => {
  const root = makeFixture({ 'generated/x.md': BANNERED });

  // Missing module: the process starts and crashes before doing any work.
  const missingModule = audit(root, [
    { document: 'generated/x.md', verification: 'command', check: ['node', '/nonexistent/module.mjs'] },
  ]);
  assert.equal(missingModule.generated[0].state, 'UNRUNNABLE');
  assert.deepEqual(kinds(missingModule), ['unrunnable-check'], 'blocking, and never STALE');
  assert.match(missingModule.findings[0].detail, /Cannot find module|ERR_MODULE_NOT_FOUND/u);

  // Spawn failure: the command does not exist at all.
  const spawnFailure = audit(root, [
    { document: 'generated/x.md', verification: 'command', check: ['rottay-no-such-command-xyz'] },
  ]);
  assert.equal(spawnFailure.generated[0].state, 'UNRUNNABLE');
  assert.deepEqual(kinds(spawnFailure), ['unrunnable-check']);
  assert.match(spawnFailure.findings[0].detail, /ENOENT/u);
});

