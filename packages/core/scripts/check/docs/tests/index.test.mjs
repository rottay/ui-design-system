test('classifyGeneratorFailure separates a clean refusal from a crash', () => {
  assert.equal(classifyGeneratorFailure({ status: 1, stderr: 'catalog is stale\n' }).state, 'STALE');
  assert.equal(classifyGeneratorFailure({ status: 1, stderr: 'Cannot find module x\n' }).state, 'UNRUNNABLE');
  assert.equal(classifyGeneratorFailure({ code: 'ENOENT', message: 'spawn failed' }).state, 'UNRUNNABLE');
  assert.equal(classifyGeneratorFailure({ signal: 'SIGKILL', status: null }).state, 'UNRUNNABLE');
});

