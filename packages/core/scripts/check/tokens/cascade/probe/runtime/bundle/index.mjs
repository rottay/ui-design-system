/**
 * @fileoverview Which CSS is authoritative, and the proof that goes with it.
 *
 * THE TRAP THIS EXISTS TO AVOID. `dist/*.css` is what the npm tarball ships,
 * while `artifacts/generated/css/verticals/<vertical>/index.css` is the repository-owned
 * generated copy. Neither is authored truth. The independent freshness gate
 * recomposes the committed artifacts from source so two stale outputs cannot
 * corroborate one another.
 *
 * So the default here is `fresh`: the bundle is recomposed IN MEMORY from
 * `src/foundation/tokens/css/**` with the same formula the staleness gate
 * uses (postcss + @tailwindcss/postcss on the modern engine, recursive
 * `@import` inlining for base and tenant, font packs ahead of base). No build
 * step, no `dist` import.
 *
 * WHAT `fresh` STILL CANNOT PRODUCE. `scripts/build/verticals/css-build/index.mjs` appends a
 * per-tenant `--ds-motion-spring: linear(...)` block derived from the compiled
 * BrandTheme modules under `dist/`. That derivation needs a build, so `fresh`
 * omits it — exactly as the staleness gate does, and for the same reason. Any
 * probe of `--ds-motion-spring` must use `--bundle dist` and accept its
 * staleness. Every other channel is complete.
 *
 * EVERY READING CARRIES ITS PROVENANCE. `resolveBundle` returns the sha256 of
 * the precise CSS string that will be handed to the browser, the mode that
 * produced it, the input paths, and — for `fresh` — the first line at which it
 * diverges from the shipped `dist` bundle. That last number is the drift, and
 * it is stated in the artifact rather than left for a reader to assume away.
 *
 * @module Tooling/ResolutionProbe/Runtime/Bundle
 */

import { createHash } from 'node:crypto';
import { existsSync, readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';

import { wrapModernFrameworkLayer } from '../../../../../../libraries/engine/framework/index.mjs';
import { DIST, fromCoreRoot, GENERATED_CSS, SRC_CSS } from '../../foundation/paths/index.mjs';
import { VERTICALS } from '../../foundation/scope/index.mjs';

const require = createRequire(import.meta.url);

export const BUNDLE_MODES = Object.freeze(['fresh', 'dist', 'generated']);

// --- helpers, kept formula-identical to scripts/build/verticals/css-build/index.mjs ---

function readFile(path) {
  if (!existsSync(path)) throw new Error(`resolution-probe: missing CSS input: ${path}`);
  return readFileSync(path, 'utf-8');
}

function unwrapRegisteredCustomProperties(css) {
  return css.replace(
    /@layer base \{\n  @property --radialprogress \{\n    syntax: "<percentage>";\n    inherits: true;\n    initial-value: 0%;\n  \}\n\}\n/g,
    '@property --radialprogress {\n  syntax: "<percentage>";\n  inherits: true;\n  initial-value: 0%;\n}\n',
  );
}

function resolveImports(css, baseDir) {
  return css.replace(
    /@import\s+['"](\.[^'"]+)['"]\s*(layer\([^)]+\))?\s*;/g,
    (match, importPath, layerDirective) => {
      const fullPath = resolve(baseDir, importPath);
      if (!existsSync(fullPath)) return `/* unresolved: ${match} */`;
      let content = readFileSync(fullPath, 'utf-8');
      content = resolveImports(content, dirname(fullPath));
      if (layerDirective) {
        const layerName = layerDirective.replace('layer(', '').replace(')', '');
        return `@layer ${layerName} {\n${content}\n}`;
      }
      return content;
    },
  );
}

function fontPackBundle(fontPacks) {
  return fontPacks
    .map((fontPack) =>
      readFile(
        resolve(SRC_CSS, `foundation/typography/font-packs/${fontPack}/index.css`),
      ).replaceAll("url('./", "url('./fonts/"),
    )
    .join('\n');
}

function composeVerticalBundle(name, baseCss, modernEngine, tenantCss, verticalFontPacks) {
  return [
    `/* @rottay/design-system - ${name} vertical bundle */`,
    `/* Generated by scripts/build/verticals/css-build/index.mjs */`,
    `/* Structure: first-party fonts + base tokens + modern engine + ${name} tenant (unlayered, wins by specificity) */`,
    '',
    ...(verticalFontPacks
      ? ['/* === First-party vertical font packs === */', verticalFontPacks, '']
      : []),
    baseCss,
    '',
    `/* === Modern Engine (Rottay skins + Tailwind utilities) === */`,
    modernEngine,
    '',
    ...(tenantCss === null
      ? ['/* === No tenant overrides: this is the base layer as a document sees it === */']
      : [
          `/* === ${name} tenant overrides (unlayered, wins by specificity + source order) === */`,
          tenantCss,
        ]),
  ].join('\n');
}

/** Compiled once per process: the engine compile is the expensive step. */
let modernEnginePromise = null;

function compileModernEngine() {
  if (modernEnginePromise) return modernEnginePromise;
  const postcss = require('postcss');
  const tailwind = require('@tailwindcss/postcss');
  const compiledPath = resolve(SRC_CSS, 'runtime/engines/modern/compiled/index.css');
  modernEnginePromise = postcss([tailwind()])
    .process(readFile(compiledPath), { from: compiledPath })
    .then((result) => wrapModernFrameworkLayer(unwrapRegisteredCustomProperties(result.css)));
  return modernEnginePromise;
}

async function composeFresh(vertical) {
  const spec = VERTICALS[vertical];
  const modernEngine = await compileModernEngine();
  const baseCss = resolveImports(
    readFile(resolve(SRC_CSS, 'facade/entrypoints/base/index.css')),
    resolve(SRC_CSS, 'facade/entrypoints/base'),
  );
  // No artifact for the tenant-less scope — that absence IS the measurement.
  const tenantPath =
    spec.artifactDir === null
      ? null
      : resolve(SRC_CSS, `facade/artifacts/${spec.artifactDir}/index.css`);
  const tenantCss =
    tenantPath === null ? null : resolveImports(readFile(tenantPath), dirname(tenantPath));
  const css = composeVerticalBundle(
    vertical,
    baseCss,
    modernEngine,
    tenantCss,
    fontPackBundle(spec.fontPacks),
  );
  return {
    css,
    inputs: [
      fromCoreRoot(resolve(SRC_CSS, 'runtime/engines/modern/compiled/index.css')),
      fromCoreRoot(resolve(SRC_CSS, 'facade/entrypoints/base/index.css')),
      ...(tenantPath === null ? [] : [fromCoreRoot(tenantPath)]),
    ],
  };
}

export function sha256(text) {
  return createHash('sha256').update(text, 'utf8').digest('hex');
}

/** 1-based line at which two texts first differ, or null when identical. */
export function firstDifferingLine(a, b) {
  if (a === b) return null;
  const left = a.split('\n');
  const right = b.split('\n');
  const max = Math.max(left.length, right.length);
  for (let i = 0; i < max; i += 1) {
    if (left[i] !== right[i]) {
      return {
        line: i + 1,
        shipped: (right[i] ?? '<end of file>').trim().slice(0, 160),
        fresh: (left[i] ?? '<end of file>').trim().slice(0, 160),
      };
    }
  }
  return null;
}

/**
 * Resolves the CSS to measure, with the provenance that justifies calling it
 * authoritative.
 *
 * @param {{vertical: string, mode?: 'fresh'|'dist'|'generated'}} input
 */
export async function resolveBundle({ vertical, mode = 'fresh' }) {
  const spec = VERTICALS[vertical];
  if (!spec) throw new Error(`unknown vertical: ${vertical}`);
  if (!BUNDLE_MODES.includes(mode)) throw new Error(`unknown bundle mode: ${mode}`);

  // Nothing ships a tenant-less bundle, so `dist`/`generated` have no answer to
  // give for it. Saying so is the point: a mode that silently fell back to
  // `fresh` would label a recomposed bundle as the shipped one.
  if (spec.distBundle === null && mode !== 'fresh') {
    throw new Error(
      `resolution-probe: --vertical ${vertical} has no shipped bundle, so --bundle ${mode} ` +
        'cannot be measured. It exists only as `fresh` (base + engine, no artifact).',
    );
  }

  const distPath = spec.distBundle === null ? null : resolve(DIST, spec.distBundle);
  const generatedPath =
    spec.generatedBundle === null ? null : resolve(GENERATED_CSS, spec.generatedBundle);
  const distCss = distPath !== null && existsSync(distPath) ? readFileSync(distPath, 'utf-8') : null;
  const generatedCss =
    generatedPath !== null && existsSync(generatedPath)
      ? readFileSync(generatedPath, 'utf-8')
      : null;

  if (mode === 'dist' || mode === 'generated') {
    const css = mode === 'dist' ? distCss : generatedCss;
    const path = mode === 'dist' ? distPath : generatedPath;
    if (css === null) throw new Error(`resolution-probe: missing bundle: ${path}`);
    return {
      mode,
      vertical,
      css,
      provenance: {
        mode,
        vertical,
        path: fromCoreRoot(path),
        sha256: sha256(css),
        bytes: css.length,
        distMatchesGenerated:
          distCss !== null && generatedCss !== null ? distCss === generatedCss : null,
        freshnessProven: false,
        freshnessNote:
          'Shipped bundle read as-is. Freshness NOT proven here: run ' +
          '`node --test scripts/build/verticals/css-freshness/index.mjs` — it recomposes these ' +
          'bundles from source and reports the first divergent line.',
      },
    };
  }

  const { css, inputs } = await composeFresh(vertical);
  const drift = distCss === null ? null : describeShippedDrift(css, distCss);
  return {
    mode,
    vertical,
    css,
    provenance: {
      mode,
      vertical,
      inputs,
      sha256: sha256(css),
      bytes: css.length,
      distMatchesGenerated:
        distCss !== null && generatedCss !== null ? distCss === generatedCss : null,
      freshnessProven: true,
      freshnessNote:
        'Recomposed in memory from src/foundation/tokens/css with the formula in ' +
        'scripts/build/verticals/css-build/index.mjs. Omits the per-tenant --ds-motion-spring tail, which ' +
        'requires compiled BrandTheme modules under dist/.',
      shippedDistDrift: drift,
    },
  };
}

/**
 * How the shipped bundle relates to the freshly recomposed one.
 *
 * IT MUST SEPARATE THE PREFIX FROM THE TAIL, because `fresh` deliberately omits
 * the per-tenant `--ds-motion-spring: linear(...)` block that
 * `scripts/build/verticals/css-build/index.mjs` appends from compiled BrandTheme modules under
 * `dist/`. Comparing whole files therefore reported EVERY spring-carrying
 * bundle as drifted, at end-of-file, for a difference the harness creates on
 * purpose — which read as "dist is behind src" on a tree where it was not, and
 * put the formula drill permanently at odds with the staleness gate.
 *
 * Whether a tail is the *sanctioned* spring block is
 * `scripts/build/verticals/css-freshness/index.mjs`'s question, and it is deliberately
 * not re-answered here: that gate owns the grammar, and a second copy of it
 * would make the two instruments' agreement worthless (they would share the
 * derivation). This reports the tail's size and says whose question it is.
 */
function describeShippedDrift(fresh, shipped) {
  if (fresh === shipped) {
    return { identical: true, prefixIdentical: true, shippedTailBytes: 0 };
  }
  if (shipped.startsWith(fresh)) {
    return {
      identical: false,
      prefixIdentical: true,
      shippedTailBytes: shipped.length - fresh.length,
      meaning:
        'The shipped bundle is this exact text plus a trailing remainder — the expected ' +
        'shape, since `fresh` omits the per-tenant --ds-motion-spring tail. Whether that ' +
        'remainder is the sanctioned spring block is scripts/build/verticals/css-freshness/index.mjs\'s ' +
        'question, not this harness\'s.',
    };
  }
  const drift = firstDifferingLine(fresh, shipped);
  return {
    identical: false,
    prefixIdentical: false,
    firstDifferingLine: drift.line,
    fresh: drift.fresh,
    shipped: drift.shipped,
    meaning:
      'dist/ and artifacts/generated/css are behind src/ WITHIN the recomposed prefix. Anything measured ' +
      'against the shipped bundle is measuring that older source.',
  };
}
