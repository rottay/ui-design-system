/**
 * Contract locks the freeze gate cannot satisfy yet, pinned in SOURCE for the
 * same reason `SEALED_BASE` is: extending one has to be a reviewed source edit,
 * never a data edit a change can make about itself.
 *
 * An obligation has three mechanical states and no override flag:
 *   symbol absent, before expiry -> printed, non-blocking
 *   symbol absent, past expiry   -> hard failure
 *   symbol present               -> hard failure until the obligation is deleted
 *                                   in the same commit that satisfies it
 */
export const OBLIGATIONS = Object.freeze([
  Object.freeze({
    id: 'engine-posture-totality',
    owner: 'DT / coordinator seat',
    phase: 'C1 (contract freeze)',
    expires: '2026-12-31',
    assertion:
      'EnginePosture is exported from infrastructure/compilers/theme/presentation/engines/contract/, '
      + 'and classic/rustic/modern each declare a TOTAL posture record.',
    symbolFile: 'packages/core/src/infrastructure/compilers/theme/presentation/engines/contract/index.ts',
    symbol: 'EnginePosture',
    why:
      'This gate is a CONTENT freeze. It must not grow a posture checker it cannot satisfy, and the '
      + 'adapter posture policy cannot be resolved before C1 — so the obligation is recorded where it '
      + 'fails loud instead of being carried as prose.',
  }),
]);

export function evaluateObligations(obligations, { readRepoFile, today }) {
  const findings = [];
  for (const obligation of obligations) {
    const source = readRepoFile(obligation.symbolFile);
    const present =
      typeof source === 'string'
      && new RegExp(`\\bexport\\b[^\\n]*\\b${obligation.symbol}\\b`).test(source);
    const expired = today > obligation.expires;
    if (present) {
      findings.push({
        id: obligation.id,
        state: 'satisfied',
        blocking: true,
        message:
          `${obligation.id}: ${obligation.symbol} now exists. The obligation has been met and must be `
          + 'deleted in the same commit that met it; a stale obligation is a claim nobody re-reads.',
      });
      continue;
    }
    findings.push({
      id: obligation.id,
      state: expired ? 'expired' : 'pending',
      blocking: expired,
      message: expired
        ? `${obligation.id}: PAST DUE (expired ${obligation.expires}, owner ${obligation.owner}). ${obligation.assertion}`
        : `${obligation.id}: pending until ${obligation.expires} (owner ${obligation.owner}, phase ${obligation.phase}).`,
    });
  }
  return findings;
}

