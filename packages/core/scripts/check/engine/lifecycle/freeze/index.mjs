/* evaluation                                                                 */
/* -------------------------------------------------------------------------- */

/**
 * Pure verdict. `entries` is the baseline map (path -> {blob, reason}); `read`
 * returns the current bytes of a path or null when it is gone.
 *
 *   relocation       — one file that moved. Byte-identical, or differing only in
 *                      module specifiers, comments and layout. Not a violation.
 *   unauthorized     — changed against the base with no allowlist entry
 *   drifted          — allowlisted, but the bytes are no longer the reviewed ones
 *   deletedAuthorized— a file pinned to authored bytes was later deleted without
 *                      re-authorizing that exact absence (`blob: null`)
 *   generated        — a build product changed under a frozen engine
 *   misKeyed         — an allowlist entry whose key is neither a tracked path nor
 *                      a deletion in this window. It authorizes NOTHING, and it
 *                      is a VIOLATION rather than a stale note: 43 written
 *                      exceptions went dark this way, under a green drill suite,
 *                      because a key that resolves on a case-insensitive
 *                      filesystem is invisible to `existsSync` and absent from
 *                      the change set git computes.
 *   stale            — an entry that no longer differs from the base
 *                      (tighten it out; never a failure)
 */
export function evaluateFreeze({ changes, entries, read, readBase = () => null, tracked = null }) {
  const unauthorized = [];
  const drifted = [];
  const deletedAuthorized = [];
  const generated = [];
  const misKeyed = [];
  const changedPaths = new Set(changes.map((c) => c.path));

  const { pairs, pairedOld, pairedNew, substitutions } = resolveRelocations({
    changes,
    readBase,
    readCurrent: read,
  });
  const relocationOf = new Map();
  for (const pair of pairs) {
    relocationOf.set(pair.deleted, pair);
    relocationOf.set(pair.added, pair);
  }
  const relocations = pairs.filter((pair) => pair.identity !== 'content-changed');
  const resolvedByRelocation = new Set();
  for (const pair of relocations) {
    resolvedByRelocation.add(pair.deleted);
    resolvedByRelocation.add(pair.added);
  }
  // A content-changed pair is ONE change, located at the new path. The deletion
  // side is the same file and is not a second, independent violation; the
  // addition side still needs its written, content-pinned exception.
  for (const pair of pairs) {
    if (pair.identity === 'content-changed') resolvedByRelocation.add(pair.deleted);
  }

  for (const change of changes) {
    if (resolvedByRelocation.has(change.path)) continue;
    const content = read(change.path);
    if (isGeneratedPath(change.path, content)) {
      generated.push(change);
      continue;
    }
    const entry = entries[change.path];
    if (!entry) {
      unauthorized.push(change);
      continue;
    }
    if (content === null) {
      if (entry.blob !== null) deletedAuthorized.push(change);
      continue;
    }
    if (sha256(content) === entry.blob) continue;
    // The pin may have been recorded before this file moved. A pin is satisfied
    // through the relocation ladder ONLY when the path really is the new side of
    // a pair in this window, so this is a relocation allowance and never a
    // general licence to reformat an authorized frozen file.
    const movedHere = pairedNew.has(change.path);
    if (
      movedHere
      && typeof entry.relocationDigest === 'string'
      && relocationDigestOf(content, change.path) === entry.relocationDigest
    ) {
      continue;
    }
    drifted.push({ ...change, authorizedBlob: entry.blob, actualBlob: sha256(content) });
  }

  const isResolvable = (path) => (tracked ? tracked.has(path) : true);
  const deletedInWindow = new Set(
    changes.filter((change) => change.status === 'D').map((change) => change.path),
  );
  const stale = [];
  for (const path of Object.keys(entries).sort()) {
    if (isResolvable(path) || deletedInWindow.has(path)) {
      if (!changedPaths.has(path)) stale.push(path);
      continue;
    }
    misKeyed.push({ path, reason: 'not a tracked path and not a deletion in this window' });
  }
  // A `blob: null` entry authorizes an ABSENCE, so it must name a real deletion.
  for (const [path, entry] of Object.entries(entries)) {
    if (entry.blob !== null) continue;
    if (deletedInWindow.has(path)) continue;
    if (misKeyed.some((finding) => finding.path === path)) continue;
    misKeyed.push({ path, reason: 'authorizes a deletion (blob: null) that is not a deletion in this window' });
  }

  return {
    unauthorized,
    drifted,
    deletedAuthorized,
    generated,
    misKeyed: misKeyed.sort((a, b) => a.path.localeCompare(b.path)),
    stale,
    relocations,
    relocationPairs: pairs,
    substitutions,
  };
}

/**
 * Advisory re-key resolution, for REPORTING only.
 *
 * A mis-keyed entry stays a violation (above). This resolves what it probably
 * meant, so the remediation is printed rather than guessed at, and it FAILS
 * LOUD when a fold is ambiguous: silently picking one of two tracked paths
 * would let a written exception migrate to the wrong file.
 */
export function resolveMisKeyed(path, tracked) {
  const fold = (value) => value.toLowerCase().replace(/[^a-z0-9/]/g, '');
  const wanted = fold(path);
  const candidates = [...tracked].filter((candidate) => fold(candidate) === wanted);
  if (candidates.length === 0) return { resolved: null, ambiguous: false };
  if (candidates.length > 1) return { resolved: null, ambiguous: true, candidates: candidates.sort() };
  return { resolved: candidates[0], ambiguous: false };
}

