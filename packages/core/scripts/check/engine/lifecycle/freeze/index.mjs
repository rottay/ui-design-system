/* -------------------------------------------------------------------------- */
/* relocation identity                                                        */
/* -------------------------------------------------------------------------- */

/**
 * `--no-renames` is deliberate: a renamed frozen file is a deletion and an
 * addition, and both sides must be accounted for. But a repository-wide
 * reorganisation then reads as two violations per file, and 62% of this
 * window's rows are exactly that. A freeze gate that cannot survive a
 * relocation does not measure the freeze; it measures the tree layout.
 *
 * Identity is therefore resolved in two ordered passes, both of which leave the
 * anti-laundering property intact:
 *
 *   1. BYTE-IDENTICAL. A deletion and an addition with the same sha256 are one
 *      file that moved. Nothing can be laundered through this: the bytes are
 *      equal.
 *   2. RELOCATION KEY. The remaining deletions are matched to additions through
 *      a canonical key plus the root substitutions DERIVED from pass 1 — never
 *      a hardcoded historical fact and never a similarity heuristic. A pair
 *      found this way is still a CHANGE: it needs a written, content-pinned
 *      exception exactly as before. What the pairing removes is the double
 *      count, not the requirement.
 *
 * A paired change whose only difference is module specifiers, comments,
 * quoting or whitespace is mechanical relocation residue, not engine work: the
 * specifier is blanked rather than rewritten, so a changed import BINDING still
 * shows, and whether the specifier resolves is `import-binding-integrity`'s
 * question, which is a separate blocking gate.
 */
const RELOCATION_SPECIFIER = 'RELOCATED_SPECIFIER';

/** Canonical key: drop a trailing `/index.<ext>`, fold case and separators. */
export function relocationKey(path) {
  return path
    .replace(/\/index(\.[a-z]+)$/, '$1')
    .toLowerCase()
    .replace(/[^a-z0-9/.]/g, '');
}

export function stripComments(text, extension) {
  let out = text.replace(/\/\*[\s\S]*?\*\//g, ' ');
  if (extension !== 'css') out = out.replace(/(^|[^:"'`\\])\/\/[^\r\n]*/g, '$1');
  return out;
}

export function blankModuleSpecifiers(text, extension) {
  if (extension === 'css') {
    return text
      .replace(/@import\s+(['"])[^'"]*\1/g, `@import ${RELOCATION_SPECIFIER}`)
      .replace(/url\(\s*(['"]?)[^)'"]*\1\s*\)/g, `url(${RELOCATION_SPECIFIER})`);
  }
  return text
    .replace(/(\bfrom\s*)(['"])[^'"]*\2/g, `$1${RELOCATION_SPECIFIER}`)
    .replace(/(\bimport\s*)(['"])[^'"]*\2/g, `$1${RELOCATION_SPECIFIER}`)
    .replace(/(\brequire\s*\(\s*)(['"])[^'"]*\2(\s*\))/g, `$1${RELOCATION_SPECIFIER}$3`)
    .replace(/(\bimport\s*\(\s*)(['"])[^'"]*\2(\s*\))/g, `$1${RELOCATION_SPECIFIER}$3`);
}

/** The bytes a relocation may not change: everything but specifiers, comments and layout. */
export function relocationNormalize(text, path) {
  const extension = path.split('.').pop();
  let out = blankModuleSpecifiers(text, extension);
  out = stripComments(out, extension);
  out = out.replace(/['"]/g, '"');
  out = out.replace(/,(\s*[)\]}])/g, '$1');
  out = out.replace(/\s+/g, ' ');
  return out.trim();
}

export function relocationDigestOf(text, path) {
  return text === null ? null : sha256(relocationNormalize(text, path));
}

/**
 * Root substitutions the window itself proves. Each byte-identical pair states
 * one old-prefix/new-prefix substitution under the canonical key; only those
 * seen at least twice are adopted, so a single coincidental pair cannot mint a
 * rewrite rule. Longest prefix wins.
 */
export function deriveRelocationSubstitutions(byteIdenticalPairs) {
  const support = new Map();
  for (const { deleted, added } of byteIdenticalPairs) {
    const from = relocationKey(deleted).split('/');
    const to = relocationKey(added).split('/');
    let head = 0;
    while (head < from.length && head < to.length && from[head] === to[head]) head += 1;
    let tail = 0;
    while (
      tail < from.length - head
      && tail < to.length - head
      && from[from.length - 1 - tail] === to[to.length - 1 - tail]
    ) {
      tail += 1;
    }
    const oldPrefix = from.slice(0, from.length - tail).join('/');
    const newPrefix = to.slice(0, to.length - tail).join('/');
    if (oldPrefix === newPrefix) continue;
    const key = `${oldPrefix}\u0000${newPrefix}`;
    support.set(key, (support.get(key) ?? 0) + 1);
  }
  return [...support.entries()]
    .filter(([, count]) => count >= 2)
    .map(([key, count]) => {
      const [oldPrefix, newPrefix] = key.split('\u0000');
      return { oldPrefix, newPrefix, support: count };
    })
    .sort((left, right) => right.oldPrefix.length - left.oldPrefix.length);
}

function applySubstitutions(key, substitutions) {
  for (const { oldPrefix, newPrefix } of substitutions) {
    if (key === oldPrefix || key.startsWith(`${oldPrefix}/`)) {
      return newPrefix + key.slice(oldPrefix.length);
    }
  }
  return key;
}

/**
 * Pair every deletion with the addition that is the same file at a new path.
 * Returns the pairing plus the derived substitutions, so the report can state
 * on what evidence a relocation was recognised.
 */
export function resolveRelocations({ changes, readBase, readCurrent }) {
  const deletions = changes.filter((change) => change.status === 'D');
  const additions = changes.filter((change) => change.status === 'A');
  const deletedText = new Map();
  for (const change of deletions) deletedText.set(change.path, readBase(change.path));
  const addedText = new Map();
  for (const change of additions) addedText.set(change.path, readCurrent(change.path));

  const byDigest = new Map();
  for (const [path, text] of deletedText) {
    if (text === null) continue;
    const digest = sha256(text);
    if (!byDigest.has(digest)) byDigest.set(digest, []);
    byDigest.get(digest).push(path);
  }
  for (const bucket of byDigest.values()) bucket.sort();

  const pairs = [];
  const pairedOld = new Set();
  const pairedNew = new Set();
  for (const path of [...addedText.keys()].sort()) {
    const text = addedText.get(path);
    if (text === null) continue;
    const bucket = byDigest.get(sha256(text));
    if (!bucket || bucket.length === 0) continue;
    const deleted = bucket.shift();
    pairs.push({ deleted, added: path, identity: 'byte-identical' });
    pairedOld.add(deleted);
    pairedNew.add(path);
  }

  const substitutions = deriveRelocationSubstitutions(pairs);
  const remainingAdds = new Map();
  for (const path of [...addedText.keys()].sort()) {
    if (pairedNew.has(path)) continue;
    const key = relocationKey(path);
    if (!remainingAdds.has(key)) remainingAdds.set(key, []);
    remainingAdds.get(key).push(path);
  }
  for (const path of [...deletedText.keys()].sort()) {
    if (pairedOld.has(path)) continue;
    const key = applySubstitutions(relocationKey(path), substitutions);
    const bucket = remainingAdds.get(key);
    if (!bucket || bucket.length === 0) continue;
    const added = bucket.shift();
    const before = deletedText.get(path);
    const after = addedText.get(added);
    const mechanical =
      before !== null
      && after !== null
      && relocationNormalize(before, path) === relocationNormalize(after, added);
    pairs.push({ deleted: path, added, identity: mechanical ? 'mechanical' : 'content-changed' });
    pairedOld.add(path);
    pairedNew.add(added);
  }

  return { pairs, pairedOld, pairedNew, substitutions };
}

