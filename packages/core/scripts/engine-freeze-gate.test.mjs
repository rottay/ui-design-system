function fixture() {
  // The baseline lives OUTSIDE the fixture repository so the repo's worktree
  // stays pristine — the tests below assert on `git status` being empty.
  const home = mkdtempSync(join(tmpdir(), 'engine-freeze-gate-'));
  const dir = join(home, 'repo');
  mkdirSync(dir, { recursive: true });
  const git = (...args) =>
    execFileSync('git', ['-C', dir, ...args], { encoding: 'utf8' }).trim();
  const write = (rel, source) => {
    const full = join(dir, rel);
    mkdirSync(dirname(full), { recursive: true });
    writeFileSync(full, source);
    return full;
  };
  git('init', '-q');
  git('config', 'user.email', 'gate@rottay.test');
  git('config', 'user.name', 'gate');
  git('config', 'commit.gpgsign', 'false');
  write(FROZEN_FILE, 'export const Box = () => null;\n');
  write(MODERN_FILE, 'export const Box = () => null;\n');
  git('add', '-A');
  git('commit', '-q', '-m', 'base');
  const base = git('rev-parse', 'HEAD');

  const baselinePath = join(home, 'baseline.json');
  const writeBaseline = (entries, baseRevision = base) =>
    writeFileSync(
      baselinePath,
      `${JSON.stringify({ schemaVersion: 2, baseRevision, entries }, null, 2)}\n`,
    );
  writeBaseline({});

  const run = (...args) =>
    spawnSync(process.execPath, [gate, '--repo', dir, '--baseline', baselinePath, ...args], {
      encoding: 'utf8',
    });

  return {
    dir,
    base,
    git,
    write,
    baselinePath,
    writeBaseline,
    readBaseline: () => JSON.parse(readFileSync(baselinePath, 'utf8')),
    run,
    cleanup: () => rmSync(home, { recursive: true, force: true }),
  };
}

test('a COMMITTED classic edit fails --check even though the worktree is clean', () => {
  const f = fixture();
  try {
    f.write(FROZEN_FILE, 'export const Box = () => "edited";\n');
    f.git('commit', '-q', '-am', 'edit a frozen engine after the freeze');
    assert.equal(f.git('status', '--porcelain'), '', 'precondition: the worktree is clean');

    const result = f.run('--check');
    assert.equal(result.status, 1, result.stdout + result.stderr);
    assert.match(result.stdout, /UNAUTHORIZED frozen-engine change \[M\]/);
    assert.match(result.stdout, new RegExp(FROZEN_FILE.replace(/[/.]/g, '\\$&')));
    assert.match(result.stderr, /FAIL — 1 frozen-engine violation/);
  } finally {
    f.cleanup();
  }
});

