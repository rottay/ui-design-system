/* ------------------------------------------------------------------------ */
/* negative drill: an import-only exception never covers a functional edit   */
/* ------------------------------------------------------------------------ */

/**
 * Relocating a shared engine module into a `folder/index` unit rewrites one
 * import line in every frozen delegation stub that consumes it, which is how
 * ten Classic/Rustic stubs came to be re-authorized on 2026-07-26 with an
 * "only the module path moved" reason. The hazard that creates is a hole: if
 * an import-only exception quietly covered whatever the file becomes NEXT, a
 * real Classic/Rustic edit could ride in behind a relocation. These drills
 * prove it cannot — the content pin re-fails on the following edit even when
 * that edit changes no import whatsoever.
 */
const stub = (from, extraProp = '') =>
  [
    "'use client';",
    "import React from 'react';",
    `import { BoxEngine } from '${from}';`,
    'export default function ClassicBox(props) {',
    `  return <BoxEngine {...props}${extraProp} />;`,
    '}',
    '',
  ].join('\n');

/** Lines present in one revision and not the other, in both directions. */
function changedLines(before, after) {
  const a = before.split('\n');
  const b = after.split('\n');
  return [...a.filter((l) => !b.includes(l)), ...b.filter((l) => !a.includes(l))].filter((l) =>
    l.trim(),
  );
}

const isImportLine = (line) => /^\s*(import|export)\b.*\bfrom\b/.test(line);

test('negative drill: an import-only exception does NOT cover a later FUNCTIONAL edit', () => {
  const f = fixture();
  try {
    // The base commit holds the pre-relocation stub.
    f.write(FROZEN_FILE, stub('../shared'));
    f.git('commit', '-q', '-am', 'stub before the relocation');
    // Re-seal the fixture window on that state so only the relocation is in view.
    f.writeBaseline({}, f.git('rev-parse', 'HEAD'));

    // 1. The relocation: exactly one changed line, and it is an import.
    const relocated = stub('../foundation');
    const relocationDelta = changedLines(stub('../shared'), relocated);
    assert.equal(relocationDelta.length, 2, 'the relocation is one line replaced');
    assert.ok(
      relocationDelta.every(isImportLine),
      `the relocation must touch imports only, got: ${relocationDelta.join(' | ')}`,
    );
    f.write(FROZEN_FILE, relocated);
    assert.equal(f.run('--check').status, 1, 'precondition: the relocation itself is a violation');

    const authorized = f.run(
      '--authorize',
      FROZEN_FILE,
      '--reason',
      'structural relocation only: the shared engine module moved to folder/index; one import line, zero functional lines',
    );
    assert.equal(authorized.status, 0, authorized.stdout + authorized.stderr);
    assert.equal(f.run('--check').status, 0, 'the reviewed import-only byte-state is green');

    // 2. The smuggled functional edit: a render change that touches NO import.
    const functional = stub('../foundation', ' className="smuggled-classic-restyle"');
    const functionalDelta = changedLines(relocated, functional);
    assert.ok(functionalDelta.length > 0);
    assert.ok(
      functionalDelta.every((line) => !isImportLine(line)),
      `the drill must change no import, got: ${functionalDelta.join(' | ')}`,
    );
    f.write(FROZEN_FILE, functional);

    const red = f.run('--check');
    assert.equal(red.status, 1, `the gate must redden on a functional edit\n${red.stdout}`);
    assert.match(red.stdout, /DRIFTED beyond its written exception/);
    assert.match(red.stderr, /FAIL — 1 frozen-engine violation/);
  } finally {
    f.cleanup();
  }
});

test('negative drill: re-authorizing one stub does not bless a SECOND frozen file', () => {
  const f = fixture();
  try {
    f.write(FROZEN_FILE, stub('../shared'));
    f.git('commit', '-q', '-am', 'stub before the relocation');
    f.writeBaseline({}, f.git('rev-parse', 'HEAD'));

    f.write(FROZEN_FILE, stub('../foundation'));
    assert.equal(
      f.run('--authorize', FROZEN_FILE, '--reason', 'structural relocation only, one import line')
        .status,
      0,
    );
    assert.equal(f.run('--check').status, 0);

    // A sibling frozen file taking the SAME relocation is still unauthorized:
    // the exception is per-path, never a glob over the relocation.
    f.write(OTHER_FROZEN_FILE, stub('../foundation'));
    const red = f.run('--check');
    assert.equal(red.status, 1, red.stdout);
    assert.match(red.stdout, /UNAUTHORIZED frozen-engine change/);
  } finally {
    f.cleanup();
  }
});

test('coverage boundary: the shared module a frozen stub delegates to is NOT frozen', () => {
  // Recorded deliberately. `engines/foundation/index.tsx` (like the
  // `engines/shared.tsx` it replaced) sits outside the freeze regex, so a
  // functional edit there changes what Classic and Rustic render without this
  // gate seeing it. Anyone reasoning about "Classic is frozen" must read the
  // delegated module too — the pin covers the stub's bytes, not its behavior.
  assert.ok(FROZEN.test('packages/core/src/ui/patterns/data/widget-board/engines/classic/index.tsx'));
  assert.ok(!FROZEN.test('packages/core/src/ui/patterns/data/widget-board/engines/foundation/index.tsx'));
  assert.ok(!FROZEN.test('packages/core/src/ui/patterns/data/widget-board/engines/shared.tsx'));
});

test('the real baseline is schema v2, pinned to the sealed base, and every entry carries a reason', () => {
  const baseline = JSON.parse(
    readFileSync(join(scriptDir, 'engine-freeze-gate.baseline.json'), 'utf8'),
  );
  assert.equal(baseline.schemaVersion, 2);
  assert.match(baseline.baseRevision, /^[0-9a-f]{40}$/);
  const entries = Object.entries(baseline.entries);
  assert.ok(entries.length > 0);
  for (const [path, entry] of entries) {
    assert.ok(FROZEN.test(path), `${path} is not a frozen path`);
    assert.match(entry.blob, /^[0-9a-f]{64}$/, `${path} has no content pin`);
    assert.ok(entry.reason.length >= 12, `${path} has no written reason`);
  }
});
