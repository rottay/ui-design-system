/**
 * Self-test for engine-freeze-gate.mjs.
 *
 * The gate's whole value is that it audits HISTORY against a sealed base rather
 * than the dirty worktree, so the fixture is a real throwaway Git repository:
 * a base commit, then a second commit that edits a frozen-engine file. A
 * dirty-tree linter reports that repo as clean (nothing is uncommitted); this
 * gate must fail it. Pure-function tests drill the collectors and the verdict
 * in isolation, mirroring container-query-gate.test.mjs's direct-import style.
 *
 * Nothing here touches the real repository: every fixture lives in a temp dir
 * and the gate is always invoked with --repo/--baseline overrides.
 */
import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
