test('--authorize records a content pin, and the SAME file drifting later fails again', () => {
  const f = fixture();
  try {
    f.write(FROZEN_FILE, 'export const Box = () => "compile fix";\n');
    f.git('commit', '-q', '-am', 'shared-contract compile fix');
    assert.equal(f.run('--check').status, 1);

    const authorized = f.run(
      '--authorize',
      FROZEN_FILE,
      '--reason',
      'minimal shared-contract compile fix; the prop type moved in the DS contract',
    );
    assert.equal(authorized.status, 0, authorized.stdout + authorized.stderr);
    const baseline = f.readBaseline();
    assert.equal(
      baseline.entries[FROZEN_FILE].blob,
      sha256('export const Box = () => "compile fix";\n'),
    );
    assert.match(baseline.entries[FROZEN_FILE].reason, /compile fix/);
    assert.equal(f.run('--check').status, 0);

    // The exception covered ONE reviewed byte-state. A further edit is not covered.
    f.write(FROZEN_FILE, 'export const Box = () => "smuggled engine work";\n');
    const drifted = f.run('--check');
    assert.equal(drifted.status, 1, drifted.stdout);
    assert.match(drifted.stdout, /DRIFTED beyond its written exception/);
  } finally {
    f.cleanup();
  }
});

