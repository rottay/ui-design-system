test('FROZEN matches classic/rustic engine folders and nothing else', () => {
  assert.ok(FROZEN.test(FROZEN_FILE));
  assert.ok(FROZEN.test(OTHER_FROZEN_FILE));
  assert.ok(!FROZEN.test(MODERN_FILE));
  // A folder that merely CONTAINS the word is not an engine folder.
  assert.ok(!FROZEN.test('packages/core/src/ui/classic-layouts/index.tsx'));
  assert.ok(!FROZEN.test('packages/core/src/ui/engines/custom/index.tsx'));
});

test('the freeze law and the consumer gate restate the SAME frozen-path regex', () => {
  // The two gates deliberately keep their own copy rather than importing each
  // other; this assertion is what stops the copies from drifting apart.
  assert.equal(FROZEN.source, FROZEN_ENGINE_PATH.source);
  assert.equal(FROZEN.flags, FROZEN_ENGINE_PATH.flags);
});

test('parseNameStatus keeps frozen paths with their status letter and drops the rest', () => {
  const rows = parseNameStatus(
    [`M\t${FROZEN_FILE}`, `A\t${OTHER_FROZEN_FILE}`, `M\t${MODERN_FILE}`, ''].join('\n'),
  );
  assert.deepEqual(rows, [
    { status: 'M', path: FROZEN_FILE, untracked: false },
    { status: 'A', path: OTHER_FROZEN_FILE, untracked: false },
  ]);
});

test('parsePorcelainUntracked reads only ?? rows (tracked edits come from the diff)', () => {
  const rows = parsePorcelainUntracked(
    [`?? ${FROZEN_FILE}`, ` M ${OTHER_FROZEN_FILE}`, `?? ${MODERN_FILE}`].join('\n'),
  );
  assert.deepEqual(rows, [{ status: 'A', path: FROZEN_FILE, untracked: true }]);
});

test('mergeChangeSets deduplicates a path reported by both collectors', () => {
  const merged = mergeChangeSets(
    [{ status: 'M', path: FROZEN_FILE, untracked: false }],
    [{ status: 'A', path: FROZEN_FILE, untracked: true }],
  );
  assert.equal(merged.length, 1);
  assert.equal(merged[0].untracked, false);
});

test('isGeneratedPath catches artifact paths and generation markers', () => {
  assert.ok(isGeneratedPath('packages/core/src/foundation/tokens/css/facade/artifacts/x.css', ''));
  assert.ok(isGeneratedPath(FROZEN_FILE, '/* @generated by the vertical CSS builder */'));
  assert.ok(isGeneratedPath(FROZEN_FILE, '// DO NOT EDIT — regenerate with pnpm icons:generate'));
  assert.ok(!isGeneratedPath(FROZEN_FILE, 'export const Box = () => null;'));
  assert.ok(!isGeneratedPath(FROZEN_FILE, null));
});

test('evaluateFreeze: an unlisted change is unauthorized, a pinned one passes', () => {
  const content = 'export const Box = () => null;\n';
  const entries = { [FROZEN_FILE]: { blob: sha256(content), reason: 'sealed' } };
  const verdict = evaluateFreeze({
    changes: [
      { status: 'M', path: FROZEN_FILE, untracked: false },
      { status: 'M', path: OTHER_FROZEN_FILE, untracked: false },
    ],
    entries,
    read: (path) => (path === FROZEN_FILE ? content : 'anything else'),
  });
  assert.deepEqual(verdict.unauthorized.map((c) => c.path), [OTHER_FROZEN_FILE]);
  assert.equal(verdict.drifted.length, 0);
});

test('evaluateFreeze: an authorized path that changed AGAIN drifts past its exception', () => {
  const entries = { [FROZEN_FILE]: { blob: sha256('reviewed'), reason: 'sealed' } };
  const verdict = evaluateFreeze({
    changes: [{ status: 'M', path: FROZEN_FILE, untracked: false }],
    entries,
    read: () => 'reviewed + a new edit',
  });
  assert.equal(verdict.unauthorized.length, 0);
  assert.deepEqual(verdict.drifted.map((c) => c.path), [FROZEN_FILE]);
});

test('evaluateFreeze: deleting an authorized file is a violation; a generated file never authorizes', () => {
  const entries = {
    [FROZEN_FILE]: { blob: sha256('reviewed'), reason: 'sealed' },
    [OTHER_FROZEN_FILE]: { blob: sha256('gen'), reason: 'sealed' },
  };
  const verdict = evaluateFreeze({
    changes: [
      { status: 'D', path: FROZEN_FILE, untracked: false },
      { status: 'M', path: OTHER_FROZEN_FILE, untracked: false },
    ],
    entries,
    read: (path) => (path === FROZEN_FILE ? null : '/* @generated */ gen'),
  });
  assert.deepEqual(verdict.deletedAuthorized.map((c) => c.path), [FROZEN_FILE]);
  assert.deepEqual(verdict.generated.map((c) => c.path), [OTHER_FROZEN_FILE]);
});

test('evaluateFreeze: an entry whose path no longer differs from the base is stale, not a failure', () => {
  const verdict = evaluateFreeze({
    changes: [],
    entries: { [FROZEN_FILE]: { blob: sha256('x'), reason: 'sealed' } },
    read: () => 'x',
  });
  assert.deepEqual(verdict.stale, [FROZEN_FILE]);
  assert.equal(verdict.unauthorized.length, 0);
});

