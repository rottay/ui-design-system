// Recompose the five generated CSS bundles in memory before the build can
// overwrite them. A committed bundle must match its current source inputs.

import { test } from "node:test";
import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { readFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

import { wrapModernFrameworkLayer } from "../../../libraries/engine/framework/index.mjs";
import { readFirstPartyRosterSource } from "../../../libraries/roster/index.mjs";
import { packageRoot as findPackageRoot } from '../../../libraries/repo-root/index.mjs';

const require = createRequire(import.meta.url);
const postcss = require("postcss");
const tailwind = require("@tailwindcss/postcss");

const HERE = dirname(fileURLToPath(import.meta.url));
const root = findPackageRoot(HERE);
const srcCss = resolve(root, "src/foundation/tokens/css");
const styles = resolve(root, "artifacts/generated/css");

// --- helpers copied verbatim from build-vertical-css.mjs -------------------

function unwrapRegisteredCustomProperties(css) {
  return css.replace(
    /@layer base \{\n  @property --radialprogress \{\n    syntax: "<percentage>";\n    inherits: true;\n    initial-value: 0%;\n  \}\n\}\n/g,
    '@property --radialprogress {\n  syntax: "<percentage>";\n  inherits: true;\n  initial-value: 0%;\n}\n'
  );
}

function readFile(path) {
  if (!existsSync(path)) throw new Error(`Missing file: ${path}`);
  return readFileSync(path, "utf-8");
}

function resolveImports(css, baseDir) {
  return css.replace(
    /@import\s+['"](\.[^'"]+)['"]\s*(layer\([^)]+\))?\s*;/g,
    (match, importPath, layerDirective) => {
      const fullPath = resolve(baseDir, importPath);
      if (!existsSync(fullPath)) return `/* unresolved: ${match} */`;
      let content = readFileSync(fullPath, "utf-8");
      content = resolveImports(content, dirname(fullPath));
      if (layerDirective) {
        const layerName = layerDirective.replace("layer(", "").replace(")", "");
        return `@layer ${layerName} {\n${content}\n}`;
      }
      return content;
    }
  );
}

// First-party vertical font packs (TASK S). Vertical identity is file-owned,
// so bithire's humanist/grotesk/mono packs are inlined ahead of baseCss in its
// bundle, and their union is inlined ahead of baseCss in the all-tenants
// bundle. Copied verbatim from build-vertical-css.mjs's fontPackBundle().
function fontPackBundle(fontPacks) {
  return fontPacks
    .map((fontPack) => {
      const fontPackPath = resolve(
        srcCss,
        `foundation/typography/font-packs/${fontPack}/index.css`
      );
      return readFile(fontPackPath).replaceAll("url('./", "url('./fonts/");
    })
    .join("\n");
}

const rosterPath = resolve(
  root,
  "src/foundation/tokens/ts/presentation/brand-themes/index.ts"
);
const verticals = readFirstPartyRosterSource(rosterPath).map((row) => ({
  name: row.slug,
  tenantFile: row.artifactPath.replace("foundation/tokens/css/", ""),
  fontPacks: row.fontPacks,
  selector: row.selector,
  springEasing: row.springEasing,
}));

function composeVerticalBundle(
  name,
  baseCss,
  modernEngine,
  tenantCss,
  verticalFontPacks
) {
  return [
    `/* @rottay/design-system - ${name} vertical bundle */`,
    `/* Generated by scripts/build/verticals/css-build/index.mjs */`,
    `/* Structure: first-party fonts + base tokens + modern engine + ${name} tenant (unlayered, wins by specificity) */`,
    "",
    ...(verticalFontPacks
      ? ["/* === First-party vertical font packs === */", verticalFontPacks, ""]
      : []),
    baseCss,
    "",
    `/* === Modern Engine (Rottay skins + Tailwind utilities) === */`,
    modernEngine,
    "",
    `/* === ${name} tenant overrides (unlayered, wins by specificity + source order) === */`,
    tenantCss,
  ].join("\n");
}

function composeStylesBundle(baseCss, modernEngine, allTenantsCss, allFontPacks) {
  return [
    `/* @rottay/design-system - full CSS bundle (all tenants) */`,
    `/* Generated by scripts/build/verticals/css-build/index.mjs */`,
    `/* Structure: base tokens + modern engine + all tenants (unlayered, wins by specificity) */`,
    `/* Production apps should use ${verticals.map(({ name }) => `styles/${name}`).join(", ")} instead. */`,
    "",
    ...(allFontPacks
      ? ["/* === First-party vertical font packs === */", allFontPacks, ""]
      : []),
    baseCss,
    "",
    `/* === Modern Engine (Rottay skins + Tailwind utilities) === */`,
    modernEngine,
    "",
    `/* === All tenant overrides (unlayered, wins by specificity + source order) === */`,
    allTenantsCss,
  ].join("\n");
}

// --- compose every bundle in memory ----------------------------------------

// Compile the modern engine from source, exactly as `build:modern-css` does
// (`postcss src/.../modern/compiled/index.css`), then apply the same unwrap step
// build-vertical-css.mjs applies to dist/modern-engine.css. No prior build.
const compiledPath = resolve(srcCss, "runtime/engines/modern/compiled/index.css");
const modernEnginePromise = postcss([tailwind()])
  .process(readFile(compiledPath), { from: compiledPath })
  .then((r) =>
    wrapModernFrameworkLayer(unwrapRegisteredCustomProperties(r.css))
  );

const modernEngine = await modernEnginePromise;

const baseCss = resolveImports(
  readFile(resolve(srcCss, "facade/entrypoints/base/index.css")),
  resolve(srcCss, "facade/entrypoints/base")
);

// Per-vertical bundles use import-resolved tenant CSS.
const expected = new Map();
for (const { name, tenantFile, fontPacks } of verticals) {
  const tenantPath = resolve(srcCss, tenantFile);
  const tenantCss = resolveImports(readFile(tenantPath), dirname(tenantPath));
  const verticalFontPacks = fontPackBundle(fontPacks);
  const bundle = composeVerticalBundle(
    name,
    baseCss,
    modernEngine,
    tenantCss,
    verticalFontPacks
  );
  expected.set(`artifacts/generated/css/verticals/${name}/index.css`, bundle);
}

// The all-tenants bundle joins the RAW artifact files (no import resolution),
// matching build-vertical-css.mjs. Its font packs are the union of every
// vertical's declared packs, deduplicated -- also matching build-vertical-css.mjs.
const allTenantsCss = verticals
  .map((v) => readFile(resolve(srcCss, v.tenantFile)))
  .join("\n");
const allFontPacks = fontPackBundle([
  ...new Set(verticals.flatMap((vertical) => vertical.fontPacks)),
]);
expected.set(
  "artifacts/generated/css/all-verticals/index.css",
  composeStylesBundle(baseCss, modernEngine, allTenantsCss, allFontPacks)
);

// artifacts/generated/css/engines/modern/index.css is checked separately (below). The tenant/index
// bundles compose base + modernEngine + tenant with a formula that is stable in
// build-vertical-css.mjs, so they are byte-pinned. artifacts/generated/css/engines/modern/index.css is the
// standalone engine bundle whose post-engine TAIL is composition-in-flux (a
// reduced-motion guard is being appended to it); that tail is sourced from
// runtime/personality/index.css, which base.css already inlines into every tenant
// bundle above, so the tail text is byte-covered there. Here we pin only that
// the standalone bundle STARTS WITH the freshly compiled engine — the drift
// class GAT-02 targets (a stale committed engine that Build would silently
// regenerate).

// --- assertions: every committed bundle matches its recomposition ----------

function firstDiffLine(committed, generated) {
  const a = committed.split("\n");
  const b = generated.split("\n");
  const max = Math.max(a.length, b.length);
  for (let i = 0; i < max; i += 1) {
    if (a[i] !== b[i]) {
      return `line ${i + 1}\n  committed: ${JSON.stringify(
        (a[i] ?? "").slice(0, 200)
      )}\n  generated: ${JSON.stringify((b[i] ?? "").slice(0, 200))}`;
    }
  }
  return "(files differ only in trailing length)";
}

// --- spring-precompute tail (TASK S) ---------------------------------------
//
// build-vertical-css.mjs appends a tenant-scoped `--ds-motion-spring: linear()`
// override derived from each BrandTheme's tension/friction (useSpring-gated).
// The executable roster projection loads both the authored themes and the
// authored spring compiler through Vite, so this pre-build check pins the exact
// selector and exact easing without depending on dist/ or duplicating a table.

function escapeRegex(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function springBlockSource(name, selector, easing) {
  return (
    String.raw`/\* === ${name} spring easing \(precomputed linear\(\) from the BrandTheme, useSpring\) === \*/\n`.replace(
      /\//g,
      "\\/"
    ) +
    `${escapeRegex(selector)} \\{\\n` +
    String.raw`  --ds-motion-spring: ${escapeRegex(easing)};\n\}`
  );
}

const SPRING_TENANTS = verticals
  .filter(({ springEasing }) => springEasing !== null)
  .map(({ name, selector, springEasing }) => ({ name, selector, springEasing }));

/** Allowed tail after the byte-pinned prefix, per committed bundle. */
function springTailRe(rel) {
  if (rel === "artifacts/generated/css/all-verticals/index.css") {
    const anyBlock = SPRING_TENANTS.map(({ name, selector, springEasing }) =>
      springBlockSource(name, selector, springEasing)
    ).join("|");
    return new RegExp(
      String.raw`^\n\n/\* === Precomputed spring easings \(per-tenant, useSpring\) === \*/\n(?:${anyBlock})(?:\n\n(?:${anyBlock}))*$`.replace(
        "/\\*",
        "\\/\\*"
      )
    );
  }
  const tenant = SPRING_TENANTS.find(
    ({ name }) => rel === `artifacts/generated/css/verticals/${name}/index.css`
  );
  if (!tenant) return null;
  return new RegExp(
    `^\\n\\n${springBlockSource(tenant.name, tenant.selector, tenant.springEasing)}$`
  );
}

for (const [rel, content] of expected) {
  test(`${rel} is in sync with its build inputs`, () => {
    const path = resolve(root, rel);
    const committed = existsSync(path) ? readFileSync(path, "utf-8") : "";
    if (committed !== content && committed.startsWith(content)) {
      const tail = committed.slice(content.length);
      const tailRe = springTailRe(rel);
      assert.ok(
        tailRe !== null && tailRe.test(tail),
        `${rel} carries a tail beyond its recomposed prefix that is not the sanctioned spring-precompute block (regenerate with: pnpm -C packages/core build:vertical-css). tail: ${JSON.stringify(
          tail.slice(0, 300)
        )}`
      );
      return;
    }
    assert.equal(
      committed,
      content,
      `${rel} is stale or hand-edited (regenerate with: pnpm -C packages/core build:vertical-css).\n${firstDiffLine(
        committed,
        content
      )}`
    );
  });
}

test("the committed modern bundle embeds the freshly compiled modern engine", () => {
  const path = resolve(styles, "engines/modern/index.css");
  const committed = existsSync(path) ? readFileSync(path, "utf-8") : "";
  assert.ok(
    committed.startsWith(modernEngine),
    `the committed modern bundle does not begin with the current source-compiled modern engine — regenerate with pnpm -C packages/core build:vertical-css. committed length ${committed.length}, engine length ${modernEngine.length}.`
  );
});
