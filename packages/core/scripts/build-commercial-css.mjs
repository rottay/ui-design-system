/**
 * Build the single commercial-kit stylesheet: `dist/commercial.css`.
 *
 * The vite library build does not emit the kit's per-component `import "./X.css"` side-effect
 * styles into the consumable dist (they are stripped), so the kit ships ALL of its CSS through
 * one style export the consumer imports once: `import "@rottay/design-system/commercial.css"`.
 * This step concatenates the ramp tokens (first, so component rules can reference the
 * variables) followed by every component's co-located CSS, in a deterministic order.
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { resolve, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const commercialDir = resolve(here, "../src/commercial");
const tokensCss = join(commercialDir, "tokens/commercial-ramp.css");
const outFile = resolve(here, "../dist/commercial.css");

/** Collect every `*.css` under src/commercial except the ramp tokens (added first). */
function collectComponentCss(dir) {
  const found = [];
  for (const entry of readdirSync(dir).sort()) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) {
      found.push(...collectComponentCss(full));
    } else if (entry.endsWith(".css") && full !== tokensCss) {
      found.push(full);
    }
  }
  return found;
}

const parts = [
  `/* @rottay/design-system/commercial.css — generated by build-commercial-css.mjs. Do not edit. */`,
  `/* tokens */`,
  readFileSync(tokensCss, "utf8"),
];

for (const file of collectComponentCss(commercialDir)) {
  const rel = file.slice(commercialDir.length + 1);
  parts.push(`/* ${rel} */`);
  parts.push(readFileSync(file, "utf8"));
}

writeFileSync(outFile, parts.join("\n\n"));
console.log(
  `build:commercial-css -> ${outFile} (${collectComponentCss(commercialDir).length} component stylesheets + tokens)`,
);
