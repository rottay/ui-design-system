function manifestFingerprint(corpus, adapter) {
  return createHash('sha256')
    .update(JSON.stringify({ corpus, adapter }))
    .digest('hex');
}

export function buildGeneratedFiles(corpus, adapter, bithirePreset) {
  const files = new Map();
  const adapterById = new Map(adapter.entries.map((entry) => [entry.id, entry]));
  const fingerprint = manifestFingerprint(corpus, adapter);

  files.set('corpus.ts', generateCorpusModule(corpus));
  files.set('phosphor-adapter.ts', generateAdapterModule(adapter, fingerprint));
  for (const entry of corpus.entries) {
    files.set(`roles/${roleFileName(entry.id)}`, generateRoleModule(entry, adapterById.get(entry.id)));
  }
  for (const pack of ICON_PACKS) {
    files.set(`packs/${pack}.tsx`, generatePackModule(pack, corpus.entries.filter((entry) => entry.pack === pack)));
  }
  files.set('facade-map/index.tsx', generateFacadeMapModule());
  files.set(
    'presets/bithire/index.tsx',
    generateBitHirePresetModule(bithirePreset, corpus),
  );
  files.set('packs/index.ts', `${GENERATED_HEADER}${ICON_PACKS.map((pack) => `export * from './${pack}';`).join('\n')}\n`);
  files.set(
    'index.ts',
    `${GENERATED_HEADER}export * from '../../../foundation/semantic/corpus/generated';\nexport * from './packs';\n`,
  );
  return files;
}

function generatedOutputPath(logicalPath) {
  if (logicalPath === 'corpus.ts') return resolve(GENERATED_CORPUS_ROOT, 'index.ts');
  if (logicalPath === 'phosphor-adapter.ts') {
    return resolve(GENERATED_ADAPTER_ROOT, 'index.ts');
  }
  return resolve(GENERATED_PRESENTATION_ROOT, logicalPath);
}

async function listFiles(root, current = root) {
  let entries;
  try {
    entries = await readdir(current, { withFileTypes: true });
  } catch (error) {
    if (error.code === 'ENOENT') return [];
    throw error;
  }
  const files = [];
  for (const entry of entries) {
    const path = resolve(current, entry.name);
    if (entry.isDirectory()) files.push(...await listFiles(root, path));
    if (entry.isFile()) files.push(relative(root, path).split(sep).join('/'));
  }
  return files.sort();
}

export async function checkGeneratedFiles(files) {
  const issues = [];
  const expectedPaths = [...files.keys()].sort();
  for (const path of expectedPaths) {
    try {
      const actual = await readFile(generatedOutputPath(path), 'utf8');
      if (actual !== files.get(path)) issues.push(`stale generated file: ${path}`);
    } catch (error) {
      if (error.code === 'ENOENT') issues.push(`missing generated file: ${path}`);
      else throw error;
    }
  }

  const expectedPhysicalPaths = new Set(
    expectedPaths.map((path) => generatedOutputPath(path)),
  );
  for (const root of GENERATED_SCAN_ROOTS) {
    for (const path of await listFiles(root)) {
      const physicalPath = resolve(root, path);
      if (!expectedPhysicalPaths.has(physicalPath)) {
        issues.push(
          `unexpected generated file: ${relative(ICON_OWNER_ROOT, physicalPath).split(sep).join('/')}`,
        );
      }
    }
  }
  return issues;
}

export async function writeGeneratedFiles(files) {
  for (const root of GENERATED_SCAN_ROOTS) {
    await rm(root, { recursive: true, force: true });
  }
  for (const path of [...files.keys()].sort()) {
    const target = generatedOutputPath(path);
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, files.get(path), 'utf8');
  }
  return files.size;
}

async function main() {
  const args = process.argv.slice(2);
  const allowed = new Set(['--check', '--help']);
  const unknown = args.filter((arg) => !allowed.has(arg));
  if (unknown.length > 0) throw new Error(`Unknown arguments: ${unknown.join(', ')}`);
  if (args.includes('--help')) {
    console.log('Usage: node scripts/generate-semantic-icons.mjs [--check]');
    return;
  }

  await access(CORPUS_PATH);
  await access(ADAPTER_PATH);
  const { corpus, adapter, bithirePreset, supplier } = await loadAndValidateManifests();
  const files = buildGeneratedFiles(corpus, adapter, bithirePreset);

  if (args.includes('--check')) {
    const issues = await checkGeneratedFiles(files);
    if (issues.length > 0) throw new Error(`Generated semantic icons are not current:\n- ${issues.join('\n- ')}`);
    console.log(`Semantic icon generation check passed: ${corpus.entries.length} roles, ${files.size} files, Phosphor ${supplier.packageVersion}.`);
    return;
  }

  const count = await writeGeneratedFiles(files);
  console.log(`Generated ${count} semantic icon files for ${corpus.entries.length} roles using Phosphor ${supplier.packageVersion}.`);
}

if (process.argv[1] && resolve(process.argv[1]) === SCRIPT_PATH) {
  main().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
