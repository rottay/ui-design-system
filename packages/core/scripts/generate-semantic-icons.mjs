function isPlainObject(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

function sameArray(left, right) {
  return left.length === right.length && left.every((value, index) => value === right[index]);
}

function unique(values) {
  return new Set(values).size === values.length;
}

function fingerprint(value) {
  return createHash('sha256').update(JSON.stringify(value)).digest('hex');
}

function exactKeys(value, allowedKeys, path, errors) {
  if (!isPlainObject(value)) {
    errors.push(`${path} must be an object`);
    return false;
  }
  for (const key of Object.keys(value)) {
    if (!allowedKeys.has(key)) errors.push(`${path}.${key} is not allowed by the schema`);
  }
  return true;
}

function requiredKeys(value, keys, path, errors) {
  for (const key of keys) {
    if (!Object.hasOwn(value, key)) errors.push(`${path}.${key} is required by the schema`);
  }
}

function throwValidation(label, errors) {
  if (errors.length > 0) {
    throw new Error(`${label} validation failed:\n- ${errors.join('\n- ')}`);
  }
}

