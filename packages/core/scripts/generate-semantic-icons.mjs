export function validateCorpusManifest(manifest) {
  const errors = [];
  const rootKeys = new Set(['$schema', 'schemaVersion', 'corpusVersion', 'expectedCounts', 'entries']);
  if (!exactKeys(manifest, rootKeys, 'corpus', errors)) {
    throwValidation('Corpus manifest', errors);
  }
  requiredKeys(manifest, ['schemaVersion', 'corpusVersion', 'expectedCounts', 'entries'], 'corpus', errors);

  if (manifest.schemaVersion !== 1) errors.push('corpus.schemaVersion must equal 1');
  if (manifest.corpusVersion !== 6) errors.push('corpus.corpusVersion must equal 6');

  const countKeys = new Set([...ICON_PACKS, 'global']);
  if (exactKeys(manifest.expectedCounts, countKeys, 'corpus.expectedCounts', errors)) {
    requiredKeys(manifest.expectedCounts, [...ICON_PACKS, 'global'], 'corpus.expectedCounts', errors);
    for (const [pack, count] of Object.entries(ICON_PACK_COUNTS)) {
      if (manifest.expectedCounts[pack] !== count) {
        errors.push(`corpus.expectedCounts.${pack} must equal ${count}`);
      }
    }
    if (manifest.expectedCounts.global !== EXPECTED_GLOBAL_COUNT) {
      errors.push(`corpus.expectedCounts.global must equal ${EXPECTED_GLOBAL_COUNT}`);
    }
  }

  if (!Array.isArray(manifest.entries)) {
    errors.push('corpus.entries must be an array');
    throwValidation('Corpus manifest', errors);
  }
  if (manifest.entries.length !== EXPECTED_GLOBAL_COUNT) {
    errors.push(`corpus.entries must contain ${EXPECTED_GLOBAL_COUNT} entries; received ${manifest.entries.length}`);
  }

  const entryKeys = new Set([
    'id',
    'pack',
    'domain',
    'intent',
    'defaultRole',
    'defaultTone',
    'autoMirror',
    'status',
    'since',
    'componentName',
    'review',
  ]);
  const requiredEntryKeys = [
    'id',
    'pack',
    'domain',
    'intent',
    'defaultRole',
    'autoMirror',
    'status',
    'since',
    'componentName',
  ];

  for (const [index, entry] of manifest.entries.entries()) {
    const path = `corpus.entries[${index}]`;
    if (!exactKeys(entry, entryKeys, path, errors)) continue;
    requiredKeys(entry, requiredEntryKeys, path, errors);

    if (typeof entry.id !== 'string' || !ID_PATTERN.test(entry.id)) errors.push(`${path}.id is not a valid semantic ID`);
    if (!VALID_PACKS.has(entry.pack)) errors.push(`${path}.pack is not a governed icon pack`);
    if (typeof entry.domain !== 'string' || entry.domain !== entry.id?.split('.')[0]) errors.push(`${path}.domain must equal the ID namespace`);
    if (typeof entry.intent !== 'string' || entry.intent.trim().length === 0) errors.push(`${path}.intent must be a non-empty string`);
    if (!VALID_ROLES.has(entry.defaultRole)) errors.push(`${path}.defaultRole is not supported`);
    if (Object.hasOwn(entry, 'defaultTone') && !VALID_TONES.has(entry.defaultTone)) errors.push(`${path}.defaultTone is not supported`);
    if (typeof entry.autoMirror !== 'boolean') errors.push(`${path}.autoMirror must be boolean`);
    if (!VALID_STATUSES.has(entry.status)) errors.push(`${path}.status must be stable or candidate`);
    if (!Number.isInteger(entry.since) || entry.since < 1 || entry.since > manifest.corpusVersion) errors.push(`${path}.since must be an integer within the corpus version`);
    if (entry.status === 'candidate' && ![4, 5, 6].includes(entry.since)) errors.push(`${path} candidate entries must have since 4, 5, or 6`);
    if (entry.status === 'stable' && entry.since > 3) errors.push(`${path} stable entries cannot have since greater than 3`);
    if (typeof entry.componentName !== 'string' || !COMPONENT_PATTERN.test(entry.componentName)) errors.push(`${path}.componentName is invalid`);
    if (typeof entry.id === 'string' && entry.componentName !== componentNameForId(entry.id)) errors.push(`${path}.componentName must be derived deterministically from its ID`);
    if (Object.hasOwn(entry, 'review') && (typeof entry.review !== 'string' || entry.review.trim().length === 0)) errors.push(`${path}.review must be a non-empty string when present`);
    if (entry.pack === 'bithire' && entry.domain !== 'bithire') errors.push(`${path} BitHire entries must use the bithire domain`);
    if (entry.pack === 'foundation' && entry.domain === 'bithire') errors.push(`${path} foundation entries cannot use the bithire domain`);
    if (Object.hasOwn(PACK_DOMAINS, entry.pack) && !PACK_DOMAINS[entry.pack].has(entry.domain)) {
      errors.push(`${path}.${entry.pack} does not govern the ${entry.domain} domain`);
    }
    if (entry.since === 5 && !Object.hasOwn(PACK_DOMAINS, entry.pack)) {
      errors.push(`${path} version 5 candidates must belong to a version 5 shared pack`);
    }
    if (Object.hasOwn(PACK_DOMAINS, entry.pack) && (entry.status !== 'candidate' || entry.since !== 5)) {
      errors.push(`${path} version 5 shared-pack entries must be candidates with since 5`);
    }
    if (entry.since === 6 && entry.pack !== 'foundation') {
      errors.push(`${path} version 6 additions must belong to the foundation pack`);
    }
  }

  const ids = manifest.entries.map((entry) => entry.id);
  const componentNames = manifest.entries.map((entry) => entry.componentName);
  if (!unique(ids)) errors.push('corpus entry IDs must be unique');
  if (!unique(componentNames)) errors.push('corpus component names must be unique');

  const stableIds = manifest.entries.filter((entry) => entry.status === 'stable').map((entry) => entry.id);
  const candidateCount = manifest.entries.filter((entry) => entry.status === 'candidate').length;
  for (const [pack, count] of Object.entries(ICON_PACK_COUNTS)) {
    const actual = manifest.entries.filter((entry) => entry.pack === pack).length;
    if (actual !== count) errors.push(`${pack} pack must contain ${count} entries; received ${actual}`);
  }
  if (!sameArray(stableIds, EXPECTED_COMPAT_CORPUS_IDS)) errors.push('stable entries must preserve the exact ordered 50-name v3 compatibility corpus');
  if (candidateCount !== 213) errors.push(`candidate set must contain 213 entries; received ${candidateCount}`);
  if (fingerprint(manifest.entries.slice(0, V4_PREFIX_COUNT)) !== V4_CORPUS_PREFIX_FINGERPRINT) {
    errors.push('the exact ordered 126-role v4 corpus prefix must remain unchanged');
  }

  throwValidation('Corpus manifest', errors);
  return manifest;
}

export function validateAdapterManifest(adapter, corpus) {
  const errors = [];
  const rootKeys = new Set(['$schema', 'schemaVersion', 'supplier', 'packageName', 'packageVersion', 'rendering', 'entries']);
  if (!exactKeys(adapter, rootKeys, 'adapter', errors)) {
    throwValidation('Phosphor adapter manifest', errors);
  }
  requiredKeys(adapter, ['schemaVersion', 'supplier', 'packageName', 'packageVersion', 'rendering', 'entries'], 'adapter', errors);
  if (adapter.schemaVersion !== 1) errors.push('adapter.schemaVersion must equal 1');
  if (adapter.supplier !== 'Phosphor') errors.push('adapter.supplier must equal Phosphor');
  if (adapter.packageName !== '@phosphor-icons/react') errors.push('adapter.packageName must equal @phosphor-icons/react');
  if (adapter.packageVersion !== '2.1.10') errors.push('adapter.packageVersion must equal 2.1.10');
  if (adapter.rendering !== 'local-ssr') errors.push('adapter.rendering must equal local-ssr');
  if (!Array.isArray(adapter.entries)) {
    errors.push('adapter.entries must be an array');
    throwValidation('Phosphor adapter manifest', errors);
  }
  if (adapter.entries.length !== corpus.entries.length) errors.push(`adapter.entries must contain ${corpus.entries.length} entries; received ${adapter.entries.length}`);

  const entryKeys = new Set(['id', 'module', 'exportName']);
  for (const [index, entry] of adapter.entries.entries()) {
    const path = `adapter.entries[${index}]`;
    if (!exactKeys(entry, entryKeys, path, errors)) continue;
    requiredKeys(entry, ['id', 'module', 'exportName'], path, errors);
    if (entry.id !== corpus.entries[index]?.id) errors.push(`${path}.id must match corpus order (${corpus.entries[index]?.id ?? 'missing'})`);
    if (typeof entry.module !== 'string' || !MODULE_PATTERN.test(entry.module)) errors.push(`${path}.module is not an exact Phosphor SSR entrypoint`);
    if (typeof entry.exportName !== 'string' || !EXPORT_PATTERN.test(entry.exportName)) errors.push(`${path}.exportName is invalid`);
    const moduleLeaf = typeof entry.module === 'string' ? entry.module.slice(MODULE_PREFIX.length) : '';
    if (entry.exportName !== `${moduleLeaf}Icon`) errors.push(`${path}.exportName must equal the SSR module leaf plus Icon`);
  }

  const ids = adapter.entries.map((entry) => entry.id);
  const modules = adapter.entries.map((entry) => entry.module);
  const exports = adapter.entries.map((entry) => entry.exportName);
  if (!unique(ids)) errors.push('adapter IDs must be unique');
  if (!unique(modules)) errors.push('adapter modules must be one-to-one and unique');
  if (!unique(exports)) errors.push('adapter exports must be one-to-one and unique');
  if (fingerprint(adapter.entries.slice(0, V4_PREFIX_COUNT)) !== V4_ADAPTER_PREFIX_FINGERPRINT) {
    errors.push('the exact ordered 126-role v4 adapter prefix must remain unchanged');
  }
  throwValidation('Phosphor adapter manifest', errors);
  return adapter;
}

export function validateIconPresetManifest(preset, corpus) {
  const errors = [];
  const rootKeys = new Set([
    'schemaVersion',
    'id',
    'corpusVersion',
    'expectedCount',
    'sourceInventory',
    'names',
  ]);
  if (!exactKeys(preset, rootKeys, 'preset', errors)) {
    throwValidation('Icon preset manifest', errors);
  }
  requiredKeys(preset, [...rootKeys], 'preset', errors);
  if (preset.schemaVersion !== 1) errors.push('preset.schemaVersion must equal 1');
  if (preset.id !== 'bithire') errors.push('preset.id must equal bithire');
  if (preset.corpusVersion !== corpus.corpusVersion) {
    errors.push(`preset.corpusVersion must equal corpus version ${corpus.corpusVersion}`);
  }
  if (!Number.isInteger(preset.expectedCount) || preset.expectedCount <= 0) {
    errors.push('preset.expectedCount must be a positive integer');
  }
  if (
    preset.sourceInventory !==
    'app-bithire/tests/architecture/_shared/icon-facade-inventory'
  ) {
    errors.push('preset.sourceInventory must identify the productive BitHire inventory');
  }
  if (!Array.isArray(preset.names)) {
    errors.push('preset.names must be an array');
    throwValidation('Icon preset manifest', errors);
  }
  if (preset.names.length !== preset.expectedCount) {
    errors.push(`preset.names must contain ${preset.expectedCount} names; received ${preset.names.length}`);
  }
  if (!unique(preset.names)) errors.push('preset.names must be unique');
  if (!sameArray(preset.names, [...preset.names].sort())) {
    errors.push('preset.names must be sorted for deterministic review');
  }
  const corpusNames = new Set(corpus.entries.map((entry) => entry.id));
  for (const [index, name] of preset.names.entries()) {
    if (typeof name !== 'string' || !corpusNames.has(name)) {
      errors.push(`preset.names[${index}] is not a governed semantic role`);
    }
  }
  throwValidation('Icon preset manifest', errors);
  return preset;
}

async function readJson(path) {
  return JSON.parse(await readFile(path, 'utf8'));
}

export async function validateLocalPhosphor(adapter) {
  const errors = [];
  let packageJson;
  try {
    packageJson = await readJson(resolve(PHOSPHOR_ROOT, 'package.json'));
  } catch (error) {
    errors.push(`cannot read local ${adapter.packageName} package metadata: ${error.message}`);
  }
  if (packageJson && packageJson.version !== adapter.packageVersion) {
    errors.push(`local ${adapter.packageName} version is ${packageJson.version}; expected ${adapter.packageVersion}`);
  }

  for (const entry of adapter.entries) {
    const leaf = entry.module.slice(MODULE_PREFIX.length);
    const declarationPath = resolve(PHOSPHOR_SSR_ROOT, `${leaf}.d.ts`);
    const runtimePath = resolve(PHOSPHOR_SSR_ROOT, `${leaf}.es.js`);
    try {
      const [declaration, runtime] = await Promise.all([
        readFile(declarationPath, 'utf8'),
        readFile(runtimePath, 'utf8'),
      ]);
      if (!declaration.includes(entry.exportName)) errors.push(`${entry.id} declaration does not export ${entry.exportName}`);
      if (!runtime.includes(entry.exportName)) errors.push(`${entry.id} runtime does not export ${entry.exportName}`);
    } catch (error) {
      errors.push(`${entry.id} cannot resolve local SSR module ${entry.module}: ${error.message}`);
    }
  }

  throwValidation('Local Phosphor adapter', errors);
  return { checked: adapter.entries.length, packageVersion: packageJson.version };
}

export async function loadAndValidateManifests() {
  const [corpus, adapter, bithirePreset] = await Promise.all([
    readJson(CORPUS_PATH),
    readJson(ADAPTER_PATH),
    readJson(BITHIRE_PRESET_PATH),
  ]);
  validateCorpusManifest(corpus);
  validateAdapterManifest(adapter, corpus);
  validateIconPresetManifest(bithirePreset, corpus);
  const supplier = await validateLocalPhosphor(adapter);
  return { corpus, adapter, bithirePreset, supplier };
}

function formatStringArray(values) {
  return values.map((value) => `  ${JSON.stringify(value)},`).join('\n');
}

function formatCorpusEntry(entry) {
  const fields = [
    `id: ${JSON.stringify(entry.id)}`,
    `pack: ${JSON.stringify(entry.pack)}`,
    `domain: ${JSON.stringify(entry.domain)}`,
    `intent: ${JSON.stringify(entry.intent)}`,
    `defaultRole: ${JSON.stringify(entry.defaultRole)}`,
  ];
  if (entry.defaultTone) fields.push(`defaultTone: ${JSON.stringify(entry.defaultTone)}`);
  fields.push(
    `autoMirror: ${entry.autoMirror}`,
    `status: ${JSON.stringify(entry.status)}`,
    `since: ${entry.since}`,
    `componentName: ${JSON.stringify(entry.componentName)}`,
  );
  if (entry.review) fields.push(`review: ${JSON.stringify(entry.review)}`);
  return `  { ${fields.join(', ')} },`;
}

