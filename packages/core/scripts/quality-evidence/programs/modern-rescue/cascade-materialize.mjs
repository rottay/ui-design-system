#!/usr/bin/env node
/**
 * cascade-materialize.mjs — WO-CRA-23 cascade, generated half (materializer).
 *
 * Emits manifest/cascade/materialized/<controlId>.json for EVERY active
 * control: the dense table variants x channels with the downstream value of
 * each variant. Facts are GENERATED, decisions are authored (adjudication
 * R1). Three materializable forms, in priority order:
 *
 *   1. numeric stops (calibration.normalizedStops with scalar value): the
 *      variant value seeds the root channel and the extracted LIVE rules are
 *      applied downstream (alias / calc-multiply with literal sibling).
 *   2. object stops (e.g. motion.dial {intensity, durationScale}): each key
 *      seeds its channel, resolved by suffix against declaredOutputs.
 *   3. authored variant effects (cascade/roots/<id>.json variants[].effects,
 *      enum roots): the dense table is the authored table, quoted with its
 *      source — for enum roots the table IS the rule (BUTTON_STYLE_RADIUS).
 *
 * A control with none of the three is NOT skipped silently: it gets a file
 * with `notMaterializable` and a cited reason (escape hatch, TS-only landing,
 * effect-by-TS-table pending its authored root, ...).
 *
 * Inputs:
 *   - manifest/controls/<id>.json            (authored: variants, outputs)
 *   - manifest/cascade/roots/<id>.json       (authored, when present)
 *   - manifest/cascade/extracted/css-edges.json (GENERATED by cascade-extract.mjs)
 *
 * Never hand-edit the output; regenerate.
 *
 * Usage: node cascade-materialize.mjs [controlId ...]   (default: all controls)
 */
import {
  readFileSync,
  readdirSync,
  mkdirSync,
  writeFileSync,
  existsSync,
} from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const CONTROLS = join(HERE, "manifest/controls");
const ROOTS = join(HERE, "manifest/cascade/roots");
const EDGES_FILE = join(HERE, "manifest/cascade/extracted/css-edges.json");
const OUT_DIR = join(HERE, "manifest/cascade/materialized");

const controlIds = process.argv.slice(2).length
  ? process.argv.slice(2)
  : readdirSync(CONTROLS)
      .filter((f) => f.endsWith(".json"))
      .map((f) => f.slice(0, -5))
      .sort();

const extracted = JSON.parse(readFileSync(EDGES_FILE, "utf8"));

/* literals: channel -> {num, unit} from the extracted literal pins */
const SINGLE_LENGTH = /^(-?(?:\d+\.?\d*|\.\d+))(px|rem|em|%|s|ms)$/;
const literals = new Map();
for (const pin of extracted.literalPins) {
  const m = SINGLE_LENGTH.exec(pin.value.trim());
  if (m) literals.set(pin.channel, { num: Number(m[1]), unit: m[2] });
}

/* inbound edges per channel (top-level refs only) */
const inbound = new Map();
for (const e of extracted.edges) {
  if (e.viaFallback) continue;
  if (!inbound.has(e.to)) inbound.set(e.to, []);
  inbound.get(e.to).push(e);
}

const fmt = (x, unit) => {
  const r = Math.round(x * 100) / 100;
  return `${Number.isInteger(r) ? r : r}${unit}`;
};
const kebab = (s) => s.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());

/** BFS over the extracted graph computing each variant's downstream value. */
function computeTable(rootChannel, variants) {
  const computed = new Map();
  const uncomputable = [];
  computed.set(rootChannel, {
    values: Object.fromEntries(variants.map((v) => [v.id, v.seed])),
    trace: [],
    unit: null,
  });
  const queue = [rootChannel];
  while (queue.length) {
    const source = queue.shift();
    const parent = computed.get(source);
    for (const [to, edges] of inbound) {
      if (computed.has(to)) continue;
      const fromHere = edges.filter((e) => e.from === source);
      if (!fromHere.length) continue;
      const e = fromHere[0];
      const site = `${e.file}:${e.line}`;
      const step = { from: e.from, to, kind: e.kind, site };
      if (e.kind === "alias" || e.kind === "identity") {
        computed.set(to, {
          values: { ...parent.values },
          trace: [...parent.trace, step],
          unit: parent.unit,
        });
        queue.push(to);
        continue;
      }
      if (e.kind === "calc-multiply" || e.kind === "data-attr-select") {
        const sibling = edges.find(
          (s) => s.from !== source && literals.has(s.from)
        );
        const base = sibling ? literals.get(sibling.from) : null;
        if (!base) {
          uncomputable.push({
            channel: to,
            reason: `${e.kind} sin operando literal resoluble (${site})`,
          });
          continue;
        }
        const values = {};
        for (const v of variants) {
          const p = parent.values[v.id];
          if (typeof p !== "number") {
            values[v.id] = p;
            continue;
          }
          values[v.id] = fmt(p * base.num, base.unit);
        }
        computed.set(to, {
          values,
          trace: [
            ...parent.trace,
            {
              ...step,
              operand: sibling.from,
              operandValue: `${base.num}${base.unit}`,
            },
          ],
          unit: base.unit,
        });
        queue.push(to);
        continue;
      }
      uncomputable.push({
        channel: to,
        reason: `kind ${e.kind} no computable por regla (${site})`,
      });
    }
  }
  computed.delete(rootChannel);
  const seenFail = new Set();
  const uncomputableUnique = uncomputable.filter((u) => {
    if (computed.has(u.channel) || seenFail.has(u.channel)) return false;
    seenFail.add(u.channel);
    return true;
  });
  const table = [...computed.entries()]
    .map(([channel, c]) => ({ channel, trace: c.trace, values: c.values }))
    .sort((a, b) => a.channel.localeCompare(b.channel));
  return { table, uncomputable: uncomputableUnique };
}

function materialize(controlId) {
  const control = JSON.parse(
    readFileSync(join(CONTROLS, `${controlId}.json`), "utf8")
  );
  const rootPath = join(ROOTS, `${controlId}.json`);
  const root = existsSync(rootPath)
    ? JSON.parse(readFileSync(rootPath, "utf8"))
    : null;
  const stops = control.calibration?.normalizedStops ?? [];
  const declared = control.declaredOutputs?.channels ?? [];
  const rootChannel = root?.rootChannel?.channel ?? declared[0] ?? null;

  const base = {
    generated: true,
    generator: "cascade-materialize.mjs",
    schemaVersion: 1,
    controlId,
    tier: control.tier,
    inputs: {
      variantsFrom: `manifest/controls/${controlId}.json (calibration.normalizedStops)`,
      rulesFrom:
        "manifest/cascade/extracted/css-edges.json (cascade-extract.mjs)",
      ...(root ? { authoredRoot: `manifest/cascade/roots/${controlId}.json` } : {}),
    },
  };

  const emit = (payload) => {
    mkdirSync(OUT_DIR, { recursive: true });
    const out = join(OUT_DIR, `${controlId}.json`);
    writeFileSync(out, JSON.stringify({ ...base, ...payload }, null, 2) + "\n");
    return out;
  };

  /* form 3: authored enum effects */
  const authoredVariants = (root?.variants ?? []).filter(
    (v) => v && v.effects && Object.keys(v.effects).length > 0
  );
  const scalarStops = stops.filter((s) => typeof s.value === "number");
  const objectStops = stops.filter(
    (s) => s.value && typeof s.value === "object" && !Array.isArray(s.value)
  );

  if (!scalarStops.length && !objectStops.length && authoredVariants.length) {
    const out = emit({
      effectKind: "perVariant-authored",
      note: "raiz enum: la tabla autorada ES la regla; se cita, no se deriva",
      variants: authoredVariants.map((v) => ({
        id: v.id,
        value: v.value ?? v.id,
        effects: v.effects,
        ...(v.pinned && Object.keys(v.pinned).length ? { pinned: v.pinned } : {}),
        ...(v.law ? { law: v.law } : {}),
      })),
    });
    console.log(`${controlId}: enum autorado, ${authoredVariants.length} variantes -> ${out}`);
    return true;
  }

  if (!scalarStops.length && !objectStops.length) {
    const reasons = {
      "chrome.anatomy":
        "enum sin vocabulario cerrado en el control; selecciona REGLAS via data-attr (11 derivations LIVE en el root autorado), no produce tabla de valores",
      "chrome.families":
        "escape hatch adjudicado: mapa familia->canal semantico; las aristas alias pertenecen al hogar de la raiz semantica (R6)",
      "density.mode":
        "efecto por tabla TS resolveDensityModeFactor (foundation/tokens/ts/foundation/base/density); el vocabulario y sus factores los declara el root autorado (pendiente)",
      "experience.profile":
        "raiz de composicion: su efecto se reparte a los ejes (dependsOn inverso de profiles.expressive); sin canal numerico propio",
      "navigation.sidebar-tone":
        "enum de cromo (mapeo a hojas sidebar del ISO Theme); efecto por tabla autorada, root pendiente",
      "palette.seeds":
        "color-set: los seeds autoran literales de color; no hay regla numerica que aplicar — la cascada de alias la emite el extractor",
      "profiles.expressive":
        "raiz multi-eje: el eje geometry aterriza via overlaps (shape.radius-scale / shape.button-style); edge/type/material via derivations LIVE del root autorado",
      "recipe-profile":
        "profile-id: seleccion gobernada de registro (fail-closed); cero descendientes en el grafo extraido (ver root autorado)",
      "responsive.posture":
        "landing 100% TS (thresholds del runtime adaptativo); sin canal gobernado — root en borrador, enmienda de rules.mjs pedida al adjudicador",
      "shape.button-style":
        "enum con tabla BUTTON_STYLE_RADIUS (appearance-posture:47-53); la tabla la cita el root autorado (pendiente, asiento Fable)",
      "surfaces.elevation-posture":
        "enum con tabla ELEVATION_PRESET (appearance-posture:80-97); la cita el root autorado (pendiente)",
      "token-overrides":
        "escape hatch adjudicado: escritura verbatim sobre allowlist cerrado (67 nombres); sin derivacion propia",
      "typography.families":
        "enum de familias tipograficas; efecto por tabla autorada (root pendiente)",
      "typography.pairing":
        "enum de pairings TYPE_PAIRINGS (foundation/tokens/ts/presentation/typography/pairings); efecto por tabla autorada (root pendiente)",
    };
    const out = emit({
      notMaterializable:
        reasons[controlId] ??
        "sin paradas numericas ni efectos de variante autorados; la cascada LIVE la emite el extractor",
    });
    console.log(`${controlId}: NOT_MATERIALIZABLE -> ${out}`);
    return false;
  }

  /* forms 1+2: numeric seeds, one table per seeded channel */
  const seeded = []; // {channel, variants:[{id,seed}]}
  if (scalarStops.length && rootChannel) {
    seeded.push({
      channel: rootChannel,
      variants: scalarStops.map((s) => ({ id: s.id, seed: s.value, ...(s.law ? { law: s.law } : {}) })),
    });
  }
  for (const s of objectStops) {
    for (const [key, val] of Object.entries(s.value)) {
      if (typeof val !== "number") continue;
      const channel = declared.find((c) => c.endsWith("-" + kebab(key)));
      if (!channel) continue;
      let entry = seeded.find((x) => x.channel === channel);
      if (!entry) {
        entry = { channel, variants: [] };
        seeded.push(entry);
      }
      entry.variants.push({ id: s.id, seed: val, ...(s.law ? { law: s.law } : {}) });
    }
  }
  if (!seeded.length) {
    const out = emit({
      notMaterializable:
        "paradas con valor objeto cuyas claves no mapean a declaredOutputs; mapeo pendiente en el root autorado",
    });
    console.log(`${controlId}: NOT_MATERIALIZABLE (seeds sin canal) -> ${out}`);
    return false;
  }

  const tables = [];
  const allUncomputable = [];
  const variantIds = [
    ...new Set(seeded.flatMap((s) => s.variants.map((v) => v.id))),
  ];
  for (const s of seeded) {
    const { table, uncomputable } = computeTable(s.channel, s.variants);
    tables.push({ rootChannel: s.channel, table });
    allUncomputable.push(...uncomputable);
  }
  const out = emit({
    effectKind: "byRule",
    variants: variantIds.map((id) => {
      const stop = stops.find((x) => x.id === id);
      return { id, value: stop?.value, ...(stop?.law ? { law: stop.law } : {}) };
    }),
    tables,
    uncomputable: allUncomputable,
  });
  console.log(
    `${controlId}: ${variantIds.length} variantes, ${seeded.length} canales semilla, ${tables.reduce((n, t) => n + t.table.length, 0)} canales computados, ${allUncomputable.length} no computables -> ${out}`
  );
  return true;
}

let ok = 0;
const notMat = [];
for (const id of controlIds) {
  if (materialize(id)) ok++;
  else notMat.push(id);
}
console.log(`materialized: ${ok}/${controlIds.length}`);
if (notMat.length) console.log(`notMaterializable: ${notMat.join(", ")}`);
